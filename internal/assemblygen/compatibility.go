// Package assemblygen renders the stable boundary used by CLI-generated
// assembly source to declare its required Kernel assembly API.
package assemblygen

import (
	"errors"
	"fmt"
	"go/format"
	"go/token"
)

var ErrInvalidPackage = errors.New("invalid generated assembly package")

const compatibilityTemplate = `// Code generated by Plystra CLI. DO NOT EDIT.

package %s

import kernelassembly "github.com/plystra/kernel/assembly"

// APIVersion is the exact Kernel assembly contract targeted by this source.
const APIVersion = kernelassembly.V1

// RequireKernelCompatibility rejects execution by an incompatible Kernel.
func RequireKernelCompatibility() error {
	return kernelassembly.RequireVersion(APIVersion)
}
`

// RenderCompatibility returns deterministic Go source for one generated
// assembly package's Kernel compatibility handshake.
func RenderCompatibility(packageName string) ([]byte, error) {
	if !token.IsIdentifier(packageName) || token.Lookup(packageName).IsKeyword() {
		return nil, ErrInvalidPackage
	}
	source, err := format.Source([]byte(fmt.Sprintf(compatibilityTemplate, packageName)))
	if err != nil {
		return nil, fmt.Errorf("format generated assembly compatibility: %w", err)
	}
	return source, nil
}
