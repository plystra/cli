package assemblygen_test

import (
	"bytes"
	"errors"
	"go/parser"
	"go/token"
	"testing"

	"github.com/plystra/cli/internal/assemblygen"
)

func TestRenderCompatibility(t *testing.T) {
	t.Parallel()

	got, err := assemblygen.RenderCompatibility("assembly")
	if err != nil {
		t.Fatalf("RenderCompatibility: %v", err)
	}
	const want = `// Code generated by Plystra CLI. DO NOT EDIT.

package assembly

import kernelassembly "github.com/plystra/kernel/assembly"

// APIVersion is the exact Kernel assembly contract targeted by this source.
const APIVersion = kernelassembly.V1

// RequireKernelCompatibility rejects execution by an incompatible Kernel.
func RequireKernelCompatibility() error {
	return kernelassembly.RequireVersion(APIVersion)
}
`
	if string(got) != want {
		t.Fatalf("RenderCompatibility() =\n%s\nwant:\n%s", got, want)
	}
	if _, err := parser.ParseFile(token.NewFileSet(), "compatibility_gen.go", got, parser.AllErrors); err != nil {
		t.Fatalf("parse generated compatibility source: %v", err)
	}

	again, err := assemblygen.RenderCompatibility("assembly")
	if err != nil {
		t.Fatalf("second RenderCompatibility: %v", err)
	}
	if !bytes.Equal(got, again) {
		t.Fatal("repeated rendering produced different bytes")
	}
}

func TestRenderCompatibilityRejectsInvalidPackage(t *testing.T) {
	t.Parallel()

	for _, packageName := range []string{"", "with-dash", "two words", "package", "123assembly"} {
		packageName := packageName
		t.Run(packageName, func(t *testing.T) {
			t.Parallel()
			got, err := assemblygen.RenderCompatibility(packageName)
			if !errors.Is(err, assemblygen.ErrInvalidPackage) {
				t.Fatalf("RenderCompatibility(%q) error = %v, want ErrInvalidPackage", packageName, err)
			}
			if got != nil {
				t.Fatalf("RenderCompatibility(%q) returned %q, want nil", packageName, got)
			}
		})
	}
}
