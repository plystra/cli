package assemblygen

import (
	"errors"
	"fmt"
	"go/format"
	"path"
	"sort"
	"strconv"
	"strings"

	"github.com/plystra/cli/internal/configurationgen"
	"github.com/plystra/cli/internal/pluginid"
	"golang.org/x/mod/module"
)

// ProvidersPath is the application-relative selected-provider source path.
const ProvidersPath = "generated/go/assembly/providers_gen.go"

var (
	// ErrRenderProviders reports invalid selected-plugin provenance or a
	// generated provider source formatting failure.
	ErrRenderProviders = errors.New("render selected plugin providers")
	// ErrInvalidProvider reports one selected plugin that cannot be imported
	// through the required direct-child Go Module layout.
	ErrInvalidProvider = errors.New("invalid selected plugin provider")
	// ErrDuplicateProvider reports repeated Plugin IDs, import paths, or
	// generated configuration symbols in one provider plan.
	ErrDuplicateProvider = errors.New("duplicate selected plugin provider")
)

// ProviderInput is the complete public build provenance needed to import and
// construct one selected plugin. It contains no runtime configuration values.
type ProviderInput struct {
	PluginID   string
	ModulePath string
	ImportPath string
}

type plannedProvider struct {
	ProviderInput
	configurationNames configurationgen.GoNames
	pluginAlias        string
	configurationAlias string
}

type importSpec struct {
	alias string
	path  string
}

// RenderProviders emits the immutable runtime construction boundary for every
// selected plugin. The generated source extracts private values only at
// startup, rejects stale configuration before invoking constructors, and
// never embeds application runtime values or Secret reference targets.
func RenderProviders(inputs []ProviderInput) ([]byte, error) {
	providers, imports, err := planProviders(inputs)
	if err != nil {
		return nil, fmt.Errorf("%w: %w", ErrRenderProviders, err)
	}

	var source strings.Builder
	fmt.Fprintln(&source, "// Code generated by Plystra CLI. DO NOT EDIT.")
	fmt.Fprintln(&source)
	fmt.Fprintln(&source, "package assembly")
	fmt.Fprintln(&source)
	fmt.Fprintln(&source, "import (")
	fmt.Fprintln(&source, "\t\"context\"")
	fmt.Fprintln(&source, "\t\"errors\"")
	fmt.Fprintln(&source, "\t\"fmt\"")
	fmt.Fprintln(&source, "\t\"log/slog\"")
	fmt.Fprintln(&source)
	fmt.Fprintln(&source, "\tkernelconfiguration \"github.com/plystra/kernel/configuration\"")
	for _, imported := range imports {
		fmt.Fprintf(&source, "\t%s %s\n", imported.alias, strconv.Quote(imported.path))
	}
	fmt.Fprintln(&source, ")")
	fmt.Fprintln(&source)
	fmt.Fprintln(&source, "var (")
	fmt.Fprintln(&source, "\t// ErrProviderAssembly reports a safe selected-plugin startup failure.")
	fmt.Fprintln(&source, "\tErrProviderAssembly = errors.New(\"assemble selected plugin providers\")")
	fmt.Fprintln(&source, "\t// ErrUnselectedPluginConfiguration reports stale configuration outside the selected plugin set.")
	fmt.Fprintln(&source, "\tErrUnselectedPluginConfiguration = errors.New(\"configuration targets unselected plugin\")")
	fmt.Fprintln(&source, "\t// ErrPluginConstructor reports a selected constructor panic or nil result.")
	fmt.Fprintln(&source, "\tErrPluginConstructor = errors.New(\"plugin constructor failed\")")
	fmt.Fprintln(&source, ")")
	fmt.Fprintln(&source)
	fmt.Fprintln(&source, "// Providers is the immutable set of selected in-process plugin providers.")
	fmt.Fprintln(&source, "// Its concrete values and configuration always remain redacted.")
	fmt.Fprintln(&source, "type Providers struct {")
	for index, provider := range providers {
		fmt.Fprintf(&source, "\tplugin%d *%s.Plugin\n", index, provider.pluginAlias)
	}
	fmt.Fprintln(&source, "\tinitialized bool")
	fmt.Fprintln(&source, "}")
	fmt.Fprintln(&source)
	fmt.Fprintln(&source, "// Valid reports whether all selected constructors completed successfully.")
	fmt.Fprintln(&source, "func (p Providers) Valid() bool {")
	fmt.Fprintln(&source, "\tif !p.initialized {")
	fmt.Fprintln(&source, "\t\treturn false")
	fmt.Fprintln(&source, "\t}")
	if len(providers) == 0 {
		fmt.Fprintln(&source, "\treturn true")
	} else {
		fmt.Fprint(&source, "\treturn ")
		for index := range providers {
			if index != 0 {
				fmt.Fprint(&source, " && ")
			}
			fmt.Fprintf(&source, "p.plugin%d != nil", index)
		}
		fmt.Fprintln(&source)
	}
	fmt.Fprintln(&source, "}")
	fmt.Fprintln(&source)
	fmt.Fprintln(&source, "// Len returns the selected provider count for a valid set.")
	fmt.Fprintln(&source, "func (p Providers) Len() int {")
	fmt.Fprintln(&source, "\tif !p.Valid() {")
	fmt.Fprintln(&source, "\t\treturn 0")
	fmt.Fprintln(&source, "\t}")
	fmt.Fprintf(&source, "\treturn %d\n", len(providers))
	fmt.Fprintln(&source, "}")
	fmt.Fprintln(&source)
	fmt.Fprintln(&source, "// String redacts every provider and its configuration.")
	fmt.Fprintln(&source, "func (Providers) String() string { return \"<redacted-plugin-providers>\" }")
	fmt.Fprintln(&source)
	fmt.Fprintln(&source, "// GoString prevents Go-syntax formatting from exposing provider state.")
	fmt.Fprintln(&source, "func (Providers) GoString() string { return \"<redacted-plugin-providers>\" }")
	fmt.Fprintln(&source)
	fmt.Fprintln(&source, "// Format redacts provider state for every fmt verb.")
	fmt.Fprintln(&source, "func (Providers) Format(state fmt.State, _ rune) {")
	fmt.Fprintln(&source, "\t_, _ = state.Write([]byte(\"<redacted-plugin-providers>\"))")
	fmt.Fprintln(&source, "}")
	fmt.Fprintln(&source)
	fmt.Fprintln(&source, "// LogValue redacts provider state for structured standard-library logging.")
	fmt.Fprintln(&source, "func (Providers) LogValue() slog.Value {")
	fmt.Fprintln(&source, "\treturn slog.StringValue(\"<redacted-plugin-providers>\")")
	fmt.Fprintln(&source, "}")
	fmt.Fprintln(&source)
	fmt.Fprintln(&source, "// MarshalJSON rejects accidental provider serialization.")
	fmt.Fprintln(&source, "func (Providers) MarshalJSON() ([]byte, error) {")
	fmt.Fprintln(&source, "\treturn nil, kernelconfiguration.ErrSecretExposure")
	fmt.Fprintln(&source, "}")
	fmt.Fprintln(&source)
	fmt.Fprintln(&source, "// MarshalText rejects accidental provider serialization.")
	fmt.Fprintln(&source, "func (Providers) MarshalText() ([]byte, error) {")
	fmt.Fprintln(&source, "\treturn nil, kernelconfiguration.ErrSecretExposure")
	fmt.Fprintln(&source, "}")
	fmt.Fprintln(&source)
	fmt.Fprintln(&source, "// MarshalYAML rejects accidental provider serialization.")
	fmt.Fprintln(&source, "func (Providers) MarshalYAML() (any, error) {")
	fmt.Fprintln(&source, "\treturn nil, kernelconfiguration.ErrSecretExposure")
	fmt.Fprintln(&source, "}")
	fmt.Fprintln(&source)
	fmt.Fprintln(&source, "// NewProviders validates the generated Kernel boundary, decodes exactly one")
	fmt.Fprintln(&source, "// private configuration object per selected Plugin ID, and invokes each")
	fmt.Fprintln(&source, "// selected plugin constructor exactly once.")
	fmt.Fprintln(&source, "func NewProviders(ctx context.Context, resolver *kernelconfiguration.Resolver, document []byte) (Providers, error) {")
	fmt.Fprintln(&source, "\tif err := RequireKernelCompatibility(); err != nil {")
	fmt.Fprintln(&source, "\t\treturn Providers{}, fmt.Errorf(\"%w: Kernel compatibility: %w\", ErrProviderAssembly, err)")
	fmt.Fprintln(&source, "\t}")
	fmt.Fprintln(&source, "\tconfigurations, err := kernelconfiguration.ExtractObjectMap(document, \"config\")")
	fmt.Fprintln(&source, "\tif err != nil {")
	fmt.Fprintln(&source, "\t\treturn Providers{}, fmt.Errorf(\"%w: extract runtime configuration: %w\", ErrProviderAssembly, err)")
	fmt.Fprintln(&source, "\t}")
	fmt.Fprintln(&source, "\tfor _, pluginID := range configurations.Names() {")
	if len(providers) == 0 {
		source.WriteString("\t\treturn Providers{}, fmt.Errorf(\"%w: %w %q\", ErrProviderAssembly, ErrUnselectedPluginConfiguration, pluginID)\n")
	} else {
		fmt.Fprintln(&source, "\t\tswitch pluginID {")
		fmt.Fprint(&source, "\t\tcase ")
		for index, provider := range providers {
			if index != 0 {
				fmt.Fprint(&source, ", ")
			}
			fmt.Fprint(&source, strconv.Quote(provider.PluginID))
		}
		fmt.Fprintln(&source, ":")
		fmt.Fprintln(&source, "\t\tdefault:")
		source.WriteString("\t\t\treturn Providers{}, fmt.Errorf(\"%w: %w %q\", ErrProviderAssembly, ErrUnselectedPluginConfiguration, pluginID)\n")
		fmt.Fprintln(&source, "\t\t}")
	}
	fmt.Fprintln(&source, "\t}")
	for index, provider := range providers {
		fmt.Fprintf(&source, "\tconfigurationData%d, exists := configurations.YAML(%s)\n", index, strconv.Quote(provider.PluginID))
		fmt.Fprintln(&source, "\tif !exists {")
		fmt.Fprintf(&source, "\t\tconfigurationData%d = []byte(\"{}\\n\")\n", index)
		fmt.Fprintln(&source, "\t}")
		fmt.Fprintf(&source, "\tconfiguration%d, err := %s.%s(ctx, resolver, configurationData%d)\n", index, provider.configurationAlias, provider.configurationNames.DecodeName(), index)
		fmt.Fprintf(&source, "\tclear(configurationData%d)\n", index)
		fmt.Fprintln(&source, "\tif err != nil {")
		fmt.Fprintf(&source, "\t\treturn Providers{}, fmt.Errorf(\"%%w: decode plugin %%q configuration: %%w\", ErrProviderAssembly, %s, err)\n", strconv.Quote(provider.PluginID))
		fmt.Fprintln(&source, "\t}")
	}
	for index := range providers {
		fmt.Fprintf(&source, "\tplugin%d, err := constructPlugin%d(configuration%d)\n", index, index, index)
		fmt.Fprintln(&source, "\tif err != nil {")
		fmt.Fprintln(&source, "\t\treturn Providers{}, fmt.Errorf(\"%w: %w\", ErrProviderAssembly, err)")
		fmt.Fprintln(&source, "\t}")
	}
	fmt.Fprintln(&source, "\treturn Providers{")
	for index := range providers {
		fmt.Fprintf(&source, "\t\tplugin%d: plugin%d,\n", index, index)
	}
	fmt.Fprintln(&source, "\t\tinitialized: true,")
	fmt.Fprintln(&source, "\t}, nil")
	fmt.Fprintln(&source, "}")

	for index, provider := range providers {
		fmt.Fprintln(&source)
		fmt.Fprintf(&source, "func constructPlugin%d(configuration %s.%s) (plugin *%s.Plugin, err error) {\n", index, provider.configurationAlias, provider.configurationNames.TypeName(), provider.pluginAlias)
		fmt.Fprintln(&source, "\tdefer func() {")
		fmt.Fprintln(&source, "\t\tif recover() != nil {")
		fmt.Fprintln(&source, "\t\t\tplugin = nil")
		fmt.Fprintf(&source, "\t\t\terr = fmt.Errorf(\"%%w: plugin %%q panicked\", ErrPluginConstructor, %s)\n", strconv.Quote(provider.PluginID))
		fmt.Fprintln(&source, "\t\t}")
		fmt.Fprintln(&source, "\t}()")
		fmt.Fprintf(&source, "\tplugin = %s.New(configuration)\n", provider.pluginAlias)
		fmt.Fprintln(&source, "\tif plugin == nil {")
		fmt.Fprintf(&source, "\t\treturn nil, fmt.Errorf(\"%%w: plugin %%q returned nil\", ErrPluginConstructor, %s)\n", strconv.Quote(provider.PluginID))
		fmt.Fprintln(&source, "\t}")
		fmt.Fprintln(&source, "\treturn plugin, nil")
		fmt.Fprintln(&source, "}")
	}

	formatted, err := format.Source([]byte(source.String()))
	if err != nil {
		return nil, fmt.Errorf("%w: format generated source: %v", ErrRenderProviders, err)
	}
	return append([]byte(nil), formatted...), nil
}

func planProviders(inputs []ProviderInput) ([]plannedProvider, []importSpec, error) {
	providers := make([]plannedProvider, len(inputs))
	for index, input := range inputs {
		if err := pluginid.Validate(input.PluginID); err != nil {
			return nil, nil, fmt.Errorf("%w: Plugin ID %q: %v", ErrInvalidProvider, input.PluginID, err)
		}
		if err := module.CheckPath(input.ModulePath); err != nil {
			return nil, nil, fmt.Errorf("%w: plugin %q has invalid Go Module path %q: %v", ErrInvalidProvider, input.PluginID, input.ModulePath, err)
		}
		if err := module.CheckImportPath(input.ImportPath); err != nil {
			return nil, nil, fmt.Errorf("%w: plugin %q has invalid import path %q: %v", ErrInvalidProvider, input.PluginID, input.ImportPath, err)
		}
		pluginName, found := strings.CutPrefix(input.ImportPath, input.ModulePath+"/")
		if !found || pluginName == "" || strings.Contains(pluginName, "/") {
			return nil, nil, fmt.Errorf("%w: plugin %q import path %q is not a direct child of module %q", ErrInvalidProvider, input.PluginID, input.ImportPath, input.ModulePath)
		}
		names, err := configurationgen.DeriveGoNames(pluginName)
		if err != nil {
			return nil, nil, fmt.Errorf("%w: plugin %q import path %q: %v", ErrInvalidProvider, input.PluginID, input.ImportPath, err)
		}
		providers[index] = plannedProvider{ProviderInput: input, configurationNames: names}
	}
	sort.Slice(providers, func(left, right int) bool {
		if providers[left].PluginID != providers[right].PluginID {
			return providers[left].PluginID < providers[right].PluginID
		}
		if providers[left].ModulePath != providers[right].ModulePath {
			return providers[left].ModulePath < providers[right].ModulePath
		}
		return providers[left].ImportPath < providers[right].ImportPath
	})

	pluginIDs := make(map[string]string, len(providers))
	importPaths := make(map[string]string, len(providers))
	configurationSymbols := make(map[string]string, len(providers))
	modulePaths := make(map[string]struct{}, len(providers))
	for _, provider := range providers {
		if previous, duplicate := pluginIDs[provider.PluginID]; duplicate {
			return nil, nil, fmt.Errorf("%w: Plugin ID %q is declared by %s and %s", ErrDuplicateProvider, provider.PluginID, previous, provider.ImportPath)
		}
		pluginIDs[provider.PluginID] = provider.ImportPath
		if previous, duplicate := importPaths[provider.ImportPath]; duplicate {
			return nil, nil, fmt.Errorf("%w: import path %q belongs to plugins %q and %q", ErrDuplicateProvider, provider.ImportPath, previous, provider.PluginID)
		}
		importPaths[provider.ImportPath] = provider.PluginID
		key := provider.ModulePath + "\x00" + provider.configurationNames.DecodeName()
		if previous, collision := configurationSymbols[key]; collision {
			return nil, nil, fmt.Errorf("%w: plugins %q and %q in module %q both use decoder %s", ErrDuplicateProvider, previous, provider.PluginID, provider.ModulePath, provider.configurationNames.DecodeName())
		}
		configurationSymbols[key] = provider.PluginID
		modulePaths[provider.ModulePath] = struct{}{}
	}

	modules := make([]string, 0, len(modulePaths))
	for modulePath := range modulePaths {
		modules = append(modules, modulePath)
	}
	sort.Strings(modules)
	for _, modulePath := range modules {
		configurationPath := path.Join(modulePath, "generated/go/configuration")
		if configurationPath == "github.com/plystra/kernel/configuration" {
			return nil, nil, fmt.Errorf("%w: generated configuration import path %q conflicts with the Kernel", ErrDuplicateProvider, configurationPath)
		}
		if pluginID, collision := importPaths[configurationPath]; collision {
			return nil, nil, fmt.Errorf("%w: generated configuration import path %q conflicts with plugin %q", ErrDuplicateProvider, configurationPath, pluginID)
		}
	}
	configurationAliases := make(map[string]string, len(modules))
	imports := make([]importSpec, 0, len(modules)+len(providers))
	for index, modulePath := range modules {
		alias := fmt.Sprintf("configuration%d", index)
		configurationAliases[modulePath] = alias
		imports = append(imports, importSpec{alias: alias, path: path.Join(modulePath, "generated/go/configuration")})
	}
	for index := range providers {
		if providers[index].ImportPath == "github.com/plystra/kernel/configuration" {
			return nil, nil, fmt.Errorf("%w: plugin %q import path conflicts with the Kernel configuration package", ErrDuplicateProvider, providers[index].PluginID)
		}
		providers[index].pluginAlias = fmt.Sprintf("provider%d", index)
		providers[index].configurationAlias = configurationAliases[providers[index].ModulePath]
		imports = append(imports, importSpec{alias: providers[index].pluginAlias, path: providers[index].ImportPath})
	}
	sort.Slice(imports, func(left, right int) bool { return imports[left].path < imports[right].path })
	return providers, imports, nil
}
