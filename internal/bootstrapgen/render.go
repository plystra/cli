	staticDrained := make(chan error, 1)
	go func() { staticDrained <- a.interfaces.Drain(ctx) }()
	legacyError := a.invocations.Drain(ctx)
	if err := errors.Join(<-staticDrained, legacyError); err != nil { return err }
