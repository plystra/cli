// Package bootstrapgen renders the generated runtime application bootstrap.
package bootstrapgen

import (
	"errors"
	"fmt"
	"go/format"
	"path"
	"strconv"
	"strings"
	"time"

	"golang.org/x/mod/module"
)

// Path is the application-relative generated bootstrap source path.
const Path = "generated/go/bootstrap/bootstrap_gen.go"

var (
	// ErrRender reports invalid bootstrap inputs or generated source.
	ErrRender = errors.New("render application bootstrap")
	// ErrInvalidOptions reports an invalid module path or runtime default.
	ErrInvalidOptions = errors.New("invalid application bootstrap options")
)

// Options contains the public build inputs needed by runtime bootstrap. The
// default is embedded, while the application-specific value remains in the
// runtime document and never enters generated source.
type Options struct {
	ModulePath            string
	DefaultStartupTimeout time.Duration
}

// Render emits the redacted runtime boundary that safely loads the application
// document, constructs selected providers, and owns their lifecycle.
func Render(options Options) ([]byte, error) {
	if err := module.CheckPath(options.ModulePath); err != nil {
		return nil, fmt.Errorf("%w: %w: invalid Go Module path %q", ErrRender, ErrInvalidOptions, options.ModulePath)
	}
	if options.DefaultStartupTimeout <= 0 {
		return nil, fmt.Errorf("%w: %w: default startup timeout must be positive", ErrRender, ErrInvalidOptions)
	}

	assemblyPath := path.Join(options.ModulePath, "generated/go/assembly")
	var source strings.Builder
	fmt.Fprintln(&source, "// Code generated by Plystra CLI. DO NOT EDIT.")
	fmt.Fprintln(&source)
	fmt.Fprintln(&source, "package bootstrap")
	fmt.Fprintln(&source)
	fmt.Fprintln(&source, "import (")
	fmt.Fprintln(&source, "\t\"context\"")
	fmt.Fprintln(&source, "\t\"errors\"")
	fmt.Fprintln(&source, "\t\"fmt\"")
	fmt.Fprintln(&source, "\t\"log/slog\"")
	fmt.Fprintln(&source, "\t\"strings\"")
	fmt.Fprintln(&source, "\t\"time\"")
	fmt.Fprintln(&source)
	fmt.Fprintf(&source, "\tapplicationassembly %s\n", strconv.Quote(assemblyPath))
	fmt.Fprintln(&source, "\tkernelconfiguration \"github.com/plystra/kernel/configuration\"")
	fmt.Fprintln(&source, "\tkernellifecycle \"github.com/plystra/kernel/lifecycle\"")
	fmt.Fprintln(&source, ")")
	fmt.Fprintln(&source)
	fmt.Fprintf(&source, "const defaultStartupTimeout = time.Duration(%d)\n", options.DefaultStartupTimeout)
	fmt.Fprintln(&source)
	fmt.Fprintln(&source, "var (")
	fmt.Fprintln(&source, "\t// ErrBootstrap reports a safe runtime application construction failure.")
	fmt.Fprintln(&source, "\tErrBootstrap = errors.New(\"bootstrap generated application\")")
	fmt.Fprintln(&source, "\t// ErrInvalidApplication reports an absent or incomplete generated application.")
	fmt.Fprintln(&source, "\tErrInvalidApplication = errors.New(\"invalid generated application\")")
	fmt.Fprintln(&source, "\t// ErrInvalidContext reports a nil application lifecycle context.")
	fmt.Fprintln(&source, "\tErrInvalidContext = errors.New(\"invalid generated application context\")")
	fmt.Fprintln(&source, "\t// ErrRuntimeSettings reports invalid generated-bootstrap runtime settings.")
	fmt.Fprintln(&source, "\tErrRuntimeSettings = errors.New(\"invalid runtime startup settings\")")
	fmt.Fprintln(&source, "\t// ErrApplicationStart reports a redacted provider startup failure.")
	fmt.Fprintln(&source, "\tErrApplicationStart = errors.New(\"generated application startup failed\")")
	fmt.Fprintln(&source, "\t// ErrApplicationStop reports a redacted provider shutdown failure.")
	fmt.Fprintln(&source, "\tErrApplicationStop = errors.New(\"generated application shutdown failed\")")
	fmt.Fprintln(&source, ")")
	fmt.Fprintln(&source)
	fmt.Fprintln(&source, "// Application is one constructed selected-provider set and its Kernel lifecycle.")
	fmt.Fprintln(&source, "// Provider instances and their resolved runtime configuration remain private.")
	fmt.Fprintln(&source, "type Application struct {")
	fmt.Fprintln(&source, "\tproviders      applicationassembly.Providers")
	fmt.Fprintln(&source, "\tinvocations    applicationassembly.Invocations")
	fmt.Fprintln(&source, "\tlifecycle      *kernellifecycle.Manager")
	fmt.Fprintln(&source, "\tstartupTimeout time.Duration")
	fmt.Fprintln(&source, "}")
	fmt.Fprintln(&source)
	fmt.Fprintln(&source, "// New loads one runtime document, validates startup settings, resolves Secrets,")
	fmt.Fprintln(&source, "// constructs every selected provider exactly once, and binds lifecycle order.")
	fmt.Fprintln(&source, "func New(ctx context.Context, documentPath string) (*Application, error) {")
	fmt.Fprintln(&source, "\tif ctx == nil {")
	fmt.Fprintln(&source, "\t\treturn nil, fmt.Errorf(\"%w: %w\", ErrBootstrap, ErrInvalidContext)")
	fmt.Fprintln(&source, "\t}")
	fmt.Fprintln(&source, "\tdocument, err := kernelconfiguration.LoadDocument(documentPath)")
	fmt.Fprintln(&source, "\tif err != nil {")
	fmt.Fprintln(&source, "\t\treturn nil, fmt.Errorf(\"%w: load runtime document: %w\", ErrBootstrap, err)")
	fmt.Fprintln(&source, "\t}")
	fmt.Fprintln(&source, "\tdefer clear(document)")
	fmt.Fprintln(&source)
	fmt.Fprintln(&source, "\tstartupTimeout, err := parseStartupTimeout(document)")
	fmt.Fprintln(&source, "\tif err != nil {")
	fmt.Fprintln(&source, "\t\treturn nil, fmt.Errorf(\"%w: %w\", ErrBootstrap, err)")
	fmt.Fprintln(&source, "\t}")
	fmt.Fprintln(&source, "\tresolver, err := kernelconfiguration.NewResolver(kernelconfiguration.ResolverOptions{")
	fmt.Fprintln(&source, "\t\tMaximumValueBytes: kernelconfiguration.MaximumSecretValueBytes,")
	fmt.Fprintln(&source, "\t})")
	fmt.Fprintln(&source, "\tif err != nil {")
	fmt.Fprintln(&source, "\t\treturn nil, fmt.Errorf(\"%w: initialize Secret resolver: %w\", ErrBootstrap, err)")
	fmt.Fprintln(&source, "\t}")
	fmt.Fprintln(&source, "\tproviders, invocations, err := applicationassembly.NewRuntime(ctx, resolver, document)")
	fmt.Fprintln(&source, "\tif err != nil {")
	fmt.Fprintln(&source, "\t\treturn nil, fmt.Errorf(\"%w: construct application runtime: %w\", ErrBootstrap, err)")
	fmt.Fprintln(&source, "\t}")
	fmt.Fprintln(&source, "\tmanager, err := applicationassembly.NewProviderLifecycle(providers, startupTimeout)")
	fmt.Fprintln(&source, "\tif err != nil {")
	fmt.Fprintln(&source, "\t\treturn nil, fmt.Errorf(\"%w: bind provider lifecycle: %w\", ErrBootstrap, err)")
	fmt.Fprintln(&source, "\t}")
	fmt.Fprintln(&source, "\treturn &Application{providers: providers, invocations: invocations, lifecycle: manager, startupTimeout: startupTimeout}, nil")
	fmt.Fprintln(&source, "}")
	fmt.Fprintln(&source)
	fmt.Fprintln(&source, "// Valid reports whether provider construction and lifecycle binding completed.")
	fmt.Fprintln(&source, "func (a *Application) Valid() bool {")
	fmt.Fprintln(&source, "\treturn a != nil && a.providers.Valid() && a.invocations.Valid() && a.lifecycle != nil && a.startupTimeout > 0")
	fmt.Fprintln(&source, "}")
	fmt.Fprintln(&source)
	fmt.Fprintln(&source, "// Invocations returns the immutable typed canonical application runtime.")
	fmt.Fprintln(&source, "func (a *Application) Invocations() applicationassembly.Invocations {")
	fmt.Fprintln(&source, "\tif !a.Valid() {")
	fmt.Fprintln(&source, "\t\treturn applicationassembly.Invocations{}")
	fmt.Fprintln(&source, "\t}")
	fmt.Fprintln(&source, "\treturn a.invocations")
	fmt.Fprintln(&source, "}")
	fmt.Fprintln(&source)
	fmt.Fprintln(&source, "// State returns the current provider lifecycle state.")
	fmt.Fprintln(&source, "func (a *Application) State() kernellifecycle.State {")
	fmt.Fprintln(&source, "\tif !a.Valid() {")
	fmt.Fprintln(&source, "\t\treturn \"\"")
	fmt.Fprintln(&source, "\t}")
	fmt.Fprintln(&source, "\treturn a.lifecycle.State()")
	fmt.Fprintln(&source, "}")
	fmt.Fprintln(&source)
	fmt.Fprintln(&source, "// Start starts selected lifecycle providers within timeouts.startup.")
	fmt.Fprintln(&source, "func (a *Application) Start(ctx context.Context) error {")
	fmt.Fprintln(&source, "\tif !a.Valid() {")
	fmt.Fprintln(&source, "\t\treturn fmt.Errorf(\"%w: %w\", ErrApplicationStart, ErrInvalidApplication)")
	fmt.Fprintln(&source, "\t}")
	fmt.Fprintln(&source, "\tif ctx == nil {")
	fmt.Fprintln(&source, "\t\treturn fmt.Errorf(\"%w: %w\", ErrApplicationStart, ErrInvalidContext)")
	fmt.Fprintln(&source, "\t}")
	fmt.Fprintln(&source, "\tstartupContext, cancel := context.WithTimeout(ctx, a.startupTimeout)")
	fmt.Fprintln(&source, "\tdefer cancel()")
	fmt.Fprintln(&source, "\tif err := a.lifecycle.Start(startupContext); err != nil {")
	fmt.Fprintln(&source, "\t\treturn fmt.Errorf(\"%w: %w\", ErrApplicationStart, err)")
	fmt.Fprintln(&source, "\t}")
	fmt.Fprintln(&source, "\treturn nil")
	fmt.Fprintln(&source, "}")
	fmt.Fprintln(&source)
	fmt.Fprintln(&source, "// Stop stops every active lifecycle provider in reverse generated order.")
	fmt.Fprintln(&source, "func (a *Application) Stop(ctx context.Context) error {")
	fmt.Fprintln(&source, "\tif !a.Valid() {")
	fmt.Fprintln(&source, "\t\treturn fmt.Errorf(\"%w: %w\", ErrApplicationStop, ErrInvalidApplication)")
	fmt.Fprintln(&source, "\t}")
	fmt.Fprintln(&source, "\tif ctx == nil {")
	fmt.Fprintln(&source, "\t\treturn fmt.Errorf(\"%w: %w\", ErrApplicationStop, ErrInvalidContext)")
	fmt.Fprintln(&source, "\t}")
	fmt.Fprintln(&source, "\tif err := a.lifecycle.Stop(ctx); err != nil {")
	fmt.Fprintln(&source, "\t\treturn fmt.Errorf(\"%w: %w\", ErrApplicationStop, err)")
	fmt.Fprintln(&source, "\t}")
	fmt.Fprintln(&source, "\treturn nil")
	fmt.Fprintln(&source, "}")
	fmt.Fprintln(&source)
	fmt.Fprintln(&source, "// String redacts providers and runtime configuration.")
	fmt.Fprintln(&source, "func (Application) String() string { return \"<redacted-generated-application>\" }")
	fmt.Fprintln(&source)
	fmt.Fprintln(&source, "// GoString prevents Go-syntax formatting from exposing application state.")
	fmt.Fprintln(&source, "func (Application) GoString() string { return \"<redacted-generated-application>\" }")
	fmt.Fprintln(&source)
	fmt.Fprintln(&source, "// Format redacts application state for every fmt verb.")
	fmt.Fprintln(&source, "func (Application) Format(state fmt.State, _ rune) {")
	fmt.Fprintln(&source, "\t_, _ = state.Write([]byte(\"<redacted-generated-application>\"))")
	fmt.Fprintln(&source, "}")
	fmt.Fprintln(&source)
	fmt.Fprintln(&source, "// LogValue redacts application state for structured standard-library logging.")
	fmt.Fprintln(&source, "func (Application) LogValue() slog.Value {")
	fmt.Fprintln(&source, "\treturn slog.StringValue(\"<redacted-generated-application>\")")
	fmt.Fprintln(&source, "}")
	fmt.Fprintln(&source)
	fmt.Fprintln(&source, "// MarshalJSON rejects accidental application serialization.")
	fmt.Fprintln(&source, "func (Application) MarshalJSON() ([]byte, error) {")
	fmt.Fprintln(&source, "\treturn nil, kernelconfiguration.ErrSecretExposure")
	fmt.Fprintln(&source, "}")
	fmt.Fprintln(&source)
	fmt.Fprintln(&source, "// MarshalText rejects accidental application serialization.")
	fmt.Fprintln(&source, "func (Application) MarshalText() ([]byte, error) {")
	fmt.Fprintln(&source, "\treturn nil, kernelconfiguration.ErrSecretExposure")
	fmt.Fprintln(&source, "}")
	fmt.Fprintln(&source)
	fmt.Fprintln(&source, "// MarshalYAML rejects accidental application serialization.")
	fmt.Fprintln(&source, "func (Application) MarshalYAML() (any, error) {")
	fmt.Fprintln(&source, "\treturn nil, kernelconfiguration.ErrSecretExposure")
	fmt.Fprintln(&source, "}")
	fmt.Fprintln(&source)
	fmt.Fprintln(&source, "func parseStartupTimeout(document []byte) (time.Duration, error) {")
	fmt.Fprintln(&source, "\tsettings, err := kernelconfiguration.ExtractStringMap(document, \"timeouts\")")
	fmt.Fprintln(&source, "\tif err != nil {")
	fmt.Fprintln(&source, "\t\treturn 0, fmt.Errorf(\"%w: extract timeouts: %w\", ErrRuntimeSettings, err)")
	fmt.Fprintln(&source, "\t}")
	fmt.Fprintln(&source, "\tfor _, name := range settings.Names() {")
	fmt.Fprintln(&source, "\t\tif name != \"startup\" {")
	source.WriteString("\t\t\treturn 0, fmt.Errorf(\"%w: timeouts contains unsupported setting %q\", ErrRuntimeSettings, name)\n")
	fmt.Fprintln(&source, "\t\t}")
	fmt.Fprintln(&source, "\t}")
	fmt.Fprintln(&source, "\tvalue, exists := settings.Value(\"startup\")")
	fmt.Fprintln(&source, "\tif !exists {")
	fmt.Fprintln(&source, "\t\treturn defaultStartupTimeout, nil")
	fmt.Fprintln(&source, "\t}")
	fmt.Fprintln(&source, "\tif value == \"\" || len(value) > 64 || strings.TrimSpace(value) != value || strings.ContainsRune(value, '\\x00') {")
	fmt.Fprintln(&source, "\t\treturn 0, fmt.Errorf(\"%w: timeouts.startup is malformed\", ErrRuntimeSettings)")
	fmt.Fprintln(&source, "\t}")
	fmt.Fprintln(&source, "\ttimeout, err := time.ParseDuration(value)")
	fmt.Fprintln(&source, "\tif err != nil || timeout <= 0 {")
	fmt.Fprintln(&source, "\t\treturn 0, fmt.Errorf(\"%w: timeouts.startup must be a positive Go duration\", ErrRuntimeSettings)")
	fmt.Fprintln(&source, "\t}")
	fmt.Fprintln(&source, "\treturn timeout, nil")
	fmt.Fprintln(&source, "}")

	formatted, err := format.Source([]byte(source.String()))
	if err != nil {
		return nil, fmt.Errorf("%w: format generated source: %v", ErrRender, err)
	}
	return append([]byte(nil), formatted...), nil
}
