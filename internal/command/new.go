const newUsage = `Usage:
  plystra new <project-name> [--module <go-module-path>] [--template <go-module-query>] [--plugin <name>] [--git] [--github-ci] [--interactive] [--no-agent-guidance] [--format human|json]

Options:
  --module <go-module-path> Set the Go Module path; defaults to the project name.
  --template <module-query> Create from one public, portable Plystra Project dependency.
  --plugin <name>           Create an initial root-level plugin.
  --git                     Initialize a Git repository; default is off.
  --github-ci               Include GitHub Actions CI; default is off.
  --interactive             Prompt for omitted Git and GitHub CI choices.
  --no-agent-guidance       Omit version-matched Plystra Agent guidance.
  --format human|json       Select human output or one plystra.result/v1 document.

Creation is non-interactive by default in every environment. Agent guidance is
generated by default. Only --interactive permits prompts; terminal detection
never activates them.

JSON success nests one plystra.project-created/v1 payload with the Go Module
path and relative created directory. Enter payload.directory and run
plystra check independently before treating creation as complete.

Creation records --template as a direct dependency and root template relationship.
Its linear ancestry immediately supplies the supported Interface and named
Resource baseline, including CORS, without copying source or configuration or
ranking candidates. Data inheritance remains unsupported.

Invalid inherited declarations retain their owning source and specific
diagnostic with exit 3. Ambiguous Implementation choices require a decision
with exit 4. Both failures leave the requested target absent.

Invalid Project names, explicit Go Module paths, and template queries emit
PLYSTRA_PROJECT_CREATE_NAME_INVALID, PLYSTRA_PROJECT_CREATE_MODULE_INVALID,
and PLYSTRA_PROJECT_CREATE_TEMPLATE_INVALID.

Invalid initial Plugin names and derived IDs emit
PLYSTRA_PROJECT_CREATE_PLUGIN_NAME_INVALID and
PLYSTRA_PROJECT_CREATE_PLUGIN_ID_INVALID.

An existing Project target emits PLYSTRA_PROJECT_CREATE_TARGET_EXISTS and is
never replaced or modified.

Unavailable Git emits PLYSTRA_PROJECT_CREATE_GIT_UNAVAILABLE. Git processes
that start but fail initialization emit
PLYSTRA_PROJECT_CREATE_GIT_INITIALIZATION_FAILED. Both leave no target Project.

Template dependencies must be public, portable, and generation-stable. Creation
rejects the staged Project unless immediate generation checking, applicable
JavaScript SDK dependency installation plus typecheck/build/package validation,
Project checks, the read-only Go package build, and an isolated lifecycle health
smoke all succeed. Validation-only npm output is removed before installation.
`

var (
	errNewChoicePrompt = errors.New("prompt for new project choice")
	errNewInvocation   = errors.New("invalid plystra new invocation")
)

type newArguments struct {
	projectName     string
	modulePath      string
	template        string
	plugin          string
	git             booleanChoice
	githubCI        booleanChoice
	interactive     bool
	noAgentGuidance bool
	format          commandFormat
}

type booleanChoice uint8

const (
	choiceUnspecified booleanChoice = iota
	choiceYes
)

type resolvedNewChoices struct {
	git           bool
	githubCI      bool
	agentGuidance bool
}

type newProjectPrompter func(question string, defaultValue bool) (bool, error)

type newProjectResult interface {
	ModulePath() string
	Directory() string
	Path() string
}

type newProjectCreator func(context.Context, newproject.Options) (newProjectResult, error)

type newCommandDependencies struct {
	create       newProjectCreator
	invocationID invocationIDGenerator
}

type newResultEncoder struct {
	invocationID string
	emptyEffects commandschema.Effects
}

func defaultNewCommandDependencies() newCommandDependencies {
	return newCommandDependencies{
		create: func(ctx context.Context, options newproject.Options) (newProjectResult, error) {
			return newproject.Create(ctx, options)
		},
		invocationID: generateInvocationID,
	}
}

func runNewCommand(arguments []string, stdout, stderr io.Writer, workingDirectory string, environment []string, prompt newProjectPrompter, dependencies newCommandDependencies) int {
	if len(arguments) == 2 && isHelp(arguments[1]) {
		_, _ = io.WriteString(stdout, newUsage)
		return 0
	}

	format := newCommandFormatIntent(arguments)
	output, err := newCommandOutput(format, stdout, stderr)
	if err != nil {
		return 2
	}
	options, valid := parseNewArguments(arguments)
	if !valid {
		encoder, initialized := initializeNewResultEncoder(output.diagnosticWriter(), dependencies.invocationID)
		if !initialized {
			return 8
		}
		result, err := encoder.failure(errNewInvocation)
		if err != nil {
			return 8
		}
		return writeNewResult(output, result, func() {
			writeNewInvalidInvocation(output.diagnosticWriter())
		})
	}

	choices, err := resolveNewChoices(options, prompt)
	if err != nil {
		encoder, initialized := initializeNewResultEncoder(output.diagnosticWriter(), dependencies.invocationID)
		if !initialized {
			return 8
		}
		result, buildErr := encoder.failure(err)
		if buildErr != nil {
			return 8
		}
		return writeNewResult(output, result, func() {
			writeCommandFailure(output.diagnosticWriter(), "choose new project options", err, recoveryContext{operation: "new"})
		})
	}

	encoder, initialized := initializeNewResultEncoder(output.diagnosticWriter(), dependencies.invocationID)
	if !initialized {
		return 8
	}
	if dependencies.create == nil {
		creatorErr := fmt.Errorf("%w: project creator is unavailable", newproject.ErrCreate)
		result, buildErr := encoder.failure(creatorErr)
		if buildErr != nil {
			return 8
		}
		return writeNewResult(output, result, func() {
			writeCommandFailure(output.diagnosticWriter(), "create project", creatorErr, recoveryContext{operation: "new"})
		})
	}

	ctx, cancel := context.WithTimeout(context.Background(), 5*time.Minute)
	defer cancel()
	created, createErr := dependencies.create(ctx, newproject.Options{
		Parent:          workingDirectory,
		ProjectName:     options.projectName,
		ModulePath:      options.modulePath,
		Template:        options.template,
		Plugin:          options.plugin,
		Git:             choices.git,
		GitHubCI:        choices.githubCI,
		NoAgentGuidance: !choices.agentGuidance,
		Environment:     environment,
	})
	if createErr != nil {
		result, buildErr := encoder.failure(createErr)
		if buildErr != nil {
			return 8
		}
		return writeNewResult(output, result, func() {
			writeCommandFailure(output.diagnosticWriter(), "create project", createErr, recoveryContext{operation: "new"})
		})
	}

	result, err := encoder.success(created)
	if err != nil {
		return 8
	}
	return writeNewResult(output, result, func() {
		if options.template != "" {
			_, _ = fmt.Fprintf(
				output.resultWriter(),
				"Created %s from %s\nConfiguration scaffolded\nGenerated, checked, built, and locally verified\n\nNext:\n  cd %s\n  plystra check\n",
				options.projectName,
				options.template,
				options.projectName,
			)
			return
		}
		_, _ = fmt.Fprintf(output.resultWriter(), "created %s in %s\n", created.ModulePath(), created.Path())
	})
}

func parseNewArguments(arguments []string) (newArguments, bool) {
	if len(arguments) < 2 || arguments[1] == "" || strings.HasPrefix(arguments[1], "--") {
		return newArguments{}, false
	}
	result := newArguments{projectName: arguments[1], format: commandFormatHuman}
	moduleSet := false
	templateSet := false
	pluginSet := false
	formatSet := false
	for index := 2; index < len(arguments); index++ {
		switch arguments[index] {
		case "--module":
			if moduleSet || !newArgumentValueAvailable(arguments, index) {
				return newArguments{}, false
			}
			moduleSet = true
			index++
			result.modulePath = arguments[index]
		case "--template":
			if templateSet || !newArgumentValueAvailable(arguments, index) {
				return newArguments{}, false
			}
			templateSet = true
			index++
			result.template = arguments[index]
		case "--plugin":
			if pluginSet || !newArgumentValueAvailable(arguments, index) {
				return newArguments{}, false
			}
			pluginSet = true
			index++
			result.plugin = arguments[index]
		case "--git":
			if result.git != choiceUnspecified {
				return newArguments{}, false
			}
			result.git = choiceYes
		case "--github-ci":
			if result.githubCI != choiceUnspecified {
				return newArguments{}, false
			}
			result.githubCI = choiceYes
		case "--interactive":
			if result.interactive {
				return newArguments{}, false
			}
			result.interactive = true
		case "--no-agent-guidance":
			if result.noAgentGuidance {
				return newArguments{}, false
			}
			result.noAgentGuidance = true
		case "--format":
			if formatSet || !newArgumentValueAvailable(arguments, index) {
				return newArguments{}, false
			}
			formatSet = true
			index++
			switch arguments[index] {
			case string(commandFormatHuman):
				result.format = commandFormatHuman
			case string(commandFormatJSON):
				result.format = commandFormatJSON
			default:
				return newArguments{}, false
			}
		default:
			return newArguments{}, false
		}
	}
	return result, true
}

func newArgumentValueAvailable(arguments []string, index int) bool {
	return index+1 < len(arguments) && arguments[index+1] != "" && !strings.HasPrefix(arguments[index+1], "--")
}

func newCommandFormatIntent(arguments []string) commandFormat {
	for index := 0; index+1 < len(arguments); index++ {
		if arguments[index] == "--format" && arguments[index+1] == string(commandFormatJSON) {
			return commandFormatJSON
		}
	}
	return commandFormatHuman
}

func resolveNewChoices(arguments newArguments, prompt newProjectPrompter) (resolvedNewChoices, error) {
	choices := []struct {
		value    booleanChoice
		question string
		set      func(bool)
	}{
		{value: arguments.git, question: "Initialize a Git repository?"},
		{value: arguments.githubCI, question: "Include GitHub Actions CI?"},
	}
	result := resolvedNewChoices{agentGuidance: !arguments.noAgentGuidance}
	choices[0].set = func(value bool) { result.git = value }
	choices[1].set = func(value bool) { result.githubCI = value }
	for _, choice := range choices {
		switch choice.value {
		case choiceYes:
			choice.set(true)
		case choiceUnspecified:
			if !arguments.interactive {
				choice.set(false)
				continue
			}
			if prompt == nil {
				return resolvedNewChoices{}, fmt.Errorf("%w: %s: interactive input is unavailable", errNewChoicePrompt, choice.question)
			}
			value, err := prompt(choice.question, true)
			if err != nil {
				return resolvedNewChoices{}, fmt.Errorf("%w: %s: %v", errNewChoicePrompt, choice.question, err)
			}
			choice.set(value)
		default:
			return resolvedNewChoices{}, fmt.Errorf("%w: invalid parsed choice", errNewChoicePrompt)
		}
	}
	return result, nil
}

func promptNewProject(input io.Reader, output io.Writer) newProjectPrompter {
	scanner := bufio.NewScanner(input)
	return func(question string, defaultValue bool) (bool, error) {
		if input == nil || output == nil {
			return false, errors.New("input and output are required")
		}
		suffix := " [y/N]: "
		if defaultValue {
			suffix = " [Y/n]: "
		}
		for {
			if _, err := io.WriteString(output, question+suffix); err != nil {
				return false, fmt.Errorf("write prompt: %v", err)
			}
			if !scanner.Scan() {
				if err := scanner.Err(); err != nil {
					return false, fmt.Errorf("read choice: %v", err)
				}
				return false, errors.New("input ended before a choice")
			}
			switch strings.ToLower(strings.TrimSpace(scanner.Text())) {
			case "":
				return defaultValue, nil
			case "y", "yes":
				return true, nil
			case "n", "no":
				return false, nil
			default:
				if _, err := io.WriteString(output, "Please enter yes or no.\n"); err != nil {
					return false, fmt.Errorf("write retry guidance: %v", err)
				}
			}
		}
	}
}

func initializeNewResultEncoder(stderr io.Writer, generateID invocationIDGenerator) (newResultEncoder, bool) {
	if generateID == nil {
		writeNewInitializationFailure(stderr)
		return newResultEncoder{}, false
	}
	invocationID, err := generateID()
	if err != nil {
		writeNewInitializationFailure(stderr)
		return newResultEncoder{}, false
	}
	effects, err := commandschema.NewEffects(commandschema.EffectsInput{})
	if err != nil {
		writeNewInitializationFailure(stderr)
		return newResultEncoder{}, false
	}
	encoder := newResultEncoder{invocationID: invocationID, emptyEffects: effects}
	if _, err := commandschema.NewResult(commandschema.ResultInput{
		Operation:    "new",
		InvocationID: invocationID,
		Status:       commandschema.StatusSuccess,
		Effects:      effects,
	}); err != nil {
		writeNewInitializationFailure(stderr)
		return newResultEncoder{}, false
	}
	return encoder, true
}

func writeNewInitializationFailure(stderr io.Writer) {
	_, _ = io.WriteString(stderr, "initialize plystra new result: internal failure\n")
}

func (e newResultEncoder) success(created newProjectResult) (commandschema.Result, error) {
	if created == nil {
		return commandschema.Result{}, errors.New("created Project result is nil")
	}
	payload, err := commandschema.NewProjectCreated(commandschema.ProjectCreatedInput{
		ModulePath: created.ModulePath(),
		Directory:  created.Directory(),
	})
	if err != nil {
		return commandschema.Result{}, err
	}
	effect, err := commandschema.NewEffect(commandschema.EffectInput{
		ID:            "create-project",
		Class:         commandschema.EffectProjectWrite,
		Phase:         "commit",
		Target:        created.Directory(),
		Owner:         commandschema.Owner{Module: created.ModulePath(), Path: "."},
		Reason:        "requested_project_creation",
		Reversibility: "manual",
		Verification:  []string{"plystra", "check"},
	})
	if err != nil {
		return commandschema.Result{}, err
	}
	effects, err := commandschema.NewEffects(commandschema.EffectsInput{Observed: []commandschema.Effect{effect}})
	if err != nil {
		return commandschema.Result{}, err
	}
	return commandschema.NewResult(commandschema.ResultInput{
		Operation:    "new",
		InvocationID: e.invocationID,
		Status:       commandschema.StatusChanged,
		Effects:      effects,
		Payload:      payload,
	})
}

func (e newResultEncoder) failure(err error) (commandschema.Result, error) {
	status, code, message := classifyNewFailure(err)
	diagnostic, diagnosticErr := commandschema.NewDiagnostic(commandschema.DiagnosticInput{
		Code:      code,
		Severity:  diagnosticjson.SeverityError,
		Message:   message,
		Locations: actionableDiagnosticSources(err, code),
	})
	if diagnosticErr != nil {
		return commandschema.Result{}, diagnosticErr
	}
	recovery, recoveryErr := newFailureRecovery(code)
	if recoveryErr != nil {
		return commandschema.Result{}, recoveryErr
	}
	return commandschema.NewResult(commandschema.ResultInput{
		Operation:    "new",
		InvocationID: e.invocationID,
		Status:       status,
		Diagnostics:  []commandschema.Diagnostic{diagnostic},
		Recovery:     []commandschema.Recovery{recovery},
		Effects:      e.emptyEffects,
	})
}

func classifyNewFailure(err error) (commandschema.Status, string, string) {
	switch {
	case errors.Is(err, errNewInvocation):
		return commandschema.StatusInvalidInvocation, diagnosticcode.ProjectCreateInvocationInvalid, "The plystra new invocation is invalid."
	case errors.Is(err, errNewChoicePrompt), errors.Is(err, context.Canceled):
		return commandschema.StatusCancelled, diagnosticcode.ProjectCreateCancelled, "Project creation was cancelled."
	case errors.Is(err, newproject.ErrGitUnavailable):
		return commandschema.StatusPrerequisiteMissing, diagnosticcode.ProjectCreateGitUnavailable, "Git is unavailable for requested repository initialization."
	case errors.Is(err, newproject.ErrInvalidProjectName):
		return commandschema.StatusValidationFailed, diagnosticcode.ProjectCreateNameInvalid, "The Project name is invalid."
	case errors.Is(err, newproject.ErrInvalidModulePath):
		return commandschema.StatusValidationFailed, diagnosticcode.ProjectCreateModuleInvalid, "The Go Module path is invalid."
	case errors.Is(err, newproject.ErrInvalidTemplateQuery):
		return commandschema.StatusValidationFailed, diagnosticcode.ProjectCreateTemplateInvalid, "The Project template input is invalid."
	case errors.Is(err, applicationresolve.ErrTemplate), errors.Is(err, newproject.ErrInvalidTemplate):
		return commandschema.StatusValidationFailed, diagnosticcode.TemplateInvalid, "The resolved Project template is invalid."
	case errors.Is(err, interfaceresolution.ErrAmbiguousImplementation):
		return commandschema.StatusDecisionRequired, diagnosticcode.ResolveMultipleImplementations, "The Project template requires an explicit Interface implementation choice."
	case errors.Is(err, newproject.ErrInvalidPluginName):
		return commandschema.StatusValidationFailed, diagnosticcode.ProjectCreatePluginNameInvalid, "The initial Plugin name is invalid."
	case errors.Is(err, newproject.ErrInvalidPluginID):
		return commandschema.StatusValidationFailed, diagnosticcode.ProjectCreatePluginIDInvalid, "The initial Plugin identity is invalid."
	case errors.Is(err, newproject.ErrTargetExists):
		return commandschema.StatusValidationFailed, diagnosticcode.ProjectCreateTargetExists, "The Project target already exists."
	case errors.Is(err, newproject.ErrGitInitialization):
		return commandschema.StatusExecutionFailed, diagnosticcode.ProjectCreateGitInitializationFailed, "Git repository initialization failed."
	}
	if diagnostic, found := primaryActionableDiagnostic(err, recoveryContext{operation: "new"}); found && newTemplateValidationCode(diagnostic.code) {
		return commandschema.StatusValidationFailed, diagnostic.code, "The resolved Project template contains invalid application declarations."
	}
	return commandschema.StatusExecutionFailed, diagnosticcode.ProjectCreateFailed, "Project creation failed."
}

func newTemplateValidationCode(code string) bool {
	switch code {
	case diagnosticProjectManifestInvalid, diagnosticConfigurationInvalid,
		diagnosticConstructorConfigurationSchemaInvalid, diagnosticConstructorConfigurationValuesInvalid,
		diagnosticConstructorConfigurationUnselected, diagnosticPolicyNotEnforced,
		diagnosticResolveUnknownInterface, diagnosticResolveUnknownImplementation,
		diagnosticResolveIncompatibleImplementation, diagnosticResolveMissingImplementation,
		diagnosticResolveConstructorCycle, diagnosticResolveReservedInterface,
		diagnosticResolveIntrinsicInterfaceSelection, diagnosticImplementationDeclarationInvalid,
		diagnosticImplementationConfigInvalid, diagnosticImplementationRequiredInvalid,
		diagnosticcode.ImplementationResourceInvalid,
		diagnosticImplementationOptionalInvalid, diagnosticImplementationResultInvalid,
		diagnosticImplementationConformanceInvalid, diagnosticInterfaceDeclarationInvalid,
		diagnosticInterfaceContractInvalid, diagnosticInterfaceMetadataInvalid,
		diagnosticInterfaceIDDuplicate, diagnosticAuthoredPackageInvalid,
		diagnosticcode.ResourceDeclarationInvalid, diagnosticcode.ResourceProviderDeclarationInvalid,
		diagnosticcode.ResourceProviderInvalid, diagnosticcode.ResourceContractInvalid,
		diagnosticcode.ResourceIDDuplicate, diagnosticcode.ResourceInstanceInvalid,
		diagnosticcode.ResourceBindingInvalid, diagnosticcode.ResourceBindingMissing,
		diagnosticcode.ResourceBindingAmbiguous, diagnosticcode.ResourceMetadataInvalid,
		diagnosticcode.ResourceConfigurationSchemaInvalid, diagnosticcode.ResourceConfigurationValuesInvalid:
		return true
	default:
		return false
	}
}

func newFailureRecovery(code string) (commandschema.Recovery, error) {
	if code == diagnosticcode.ProjectCreateGitUnavailable {
		return commandschema.NewRecovery(commandschema.RecoveryInput{
			ID:            "install-git",
			Kind:          commandschema.RecoverySatisfyPrerequisite,
			Target:        commandschema.RecoveryTarget{Kind: "tool", ID: "git"},
			Preconditions: []commandschema.RecoveryFact{{Kind: "available"}},
			Verification:  commandschema.Verification{WorkingDirectory: ".", Argv: []string{"git", "--version"}},
		})
	}
	id, targetKind, targetID, precondition := "resolve-project-creation-failure", "operation", "new", "failure_resolved"
	switch code {
	case diagnosticcode.ProjectCreateInvocationInvalid:
		id, targetKind, targetID, precondition = "correct-project-create-invocation", "command", "new", "valid_invocation"
	case diagnosticcode.ProjectCreateNameInvalid:
		id, targetKind, targetID, precondition = "correct-project-name", "argument", "project-name", "canonical_project_name"
	case diagnosticcode.ProjectCreateModuleInvalid:
		id, targetKind, targetID, precondition = "correct-project-module", "argument", "module", "valid_module_path"
	case diagnosticcode.ProjectCreateTemplateInvalid, diagnosticcode.TemplateInvalid, diagnosticcode.ResolveMultipleImplementations:
		id, targetKind, targetID, precondition = "correct-project-template", "argument", "template", "valid_template_input"
	case diagnosticcode.ProjectCreatePluginNameInvalid:
		id, targetKind, targetID, precondition = "correct-project-plugin-name", "argument", "plugin", "canonical_plugin_name"
	case diagnosticcode.ProjectCreatePluginIDInvalid:
		id, targetKind, targetID, precondition = "correct-project-plugin-identity", "argument", "plugin", "valid_plugin_identity"
	case diagnosticcode.ProjectCreateTargetExists:
		id, targetKind, targetID, precondition = "choose-available-project-target", "project_target", "project-directory", "target_absent"
	case diagnosticcode.ProjectCreateGitInitializationFailed:
		id, targetKind, targetID, precondition = "correct-git-initialization", "tool", "git", "git_initialization_ready"
	case diagnosticcode.ProjectCreateCancelled:
		id, targetKind, targetID, precondition = "retry-project-creation", "command", "new", "intent_confirmed"
	default:
		if newTemplateValidationCode(code) {
			id, targetKind, targetID, precondition = "correct-project-template", "argument", "template", "valid_template_input"
		}
	}
	return commandschema.NewRecovery(commandschema.RecoveryInput{
		ID:            id,
		Kind:          commandschema.RecoveryManual,
		Target:        commandschema.RecoveryTarget{Kind: targetKind, ID: targetID},
		Preconditions: []commandschema.RecoveryFact{{Kind: precondition}},
		Verification:  commandschema.Verification{WorkingDirectory: ".", Argv: []string{"plystra", "new", "--help"}},
	})
}

func writeNewResult(output commandOutput, result commandschema.Result, human func()) int {
	if output.format == commandFormatJSON {
		canonical := result.CanonicalJSON()
		canonical = append(canonical, '\n')
		if _, err := output.resultWriter().Write(canonical); err != nil {
			return 8
		}
		return result.ExitClass()
	}
	if human != nil {
		human()
	}
	return result.ExitClass()
}

func writeNewInvalidInvocation(writer io.Writer) {
	_, _ = io.WriteString(writer, newUsage)
	_, _ = fmt.Fprintf(
		writer,
		"\nRecovery:\nReview `plystra new --help`, then rerun `plystra new <project-name> [options]` with one valid argument form.\n\nDiagnostic: %s\n",
		diagnosticcode.ProjectCreateInvocationInvalid,
	)
}
