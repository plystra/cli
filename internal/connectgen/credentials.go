package connectgen

import "go/format"

const credentialsRuntimePath = "generated/go/internal/connectschema/credentials_gen.go"

func renderCredentialsRuntime() ([]byte, error) {
	return format.Source([]byte(credentialsSource))
}

const credentialsSource = `// Code generated by Plystra CLI. DO NOT EDIT.
package connectschema

import (
	"context"
	"encoding/json"
	"errors"
	"net/http"
	"sort"
	"strings"

	"github.com/plystra/kernel/capability"
	"github.com/plystra/kernel/contextmetadata"
)

const httpCredentialsKey = "plystra.http-credential-metadata/v1"

var ErrInvalidHTTPCredentials = errors.New("invalid HTTP credential metadata")

// HTTPCredentials holds frozen, unverified transport input for one invocation.
type HTTPCredentials struct { payload []byte }

func (HTTPCredentials) String() string { return "httpcredentials(redacted)" }
func (HTTPCredentials) GoString() string { return "httpcredentials(redacted)" }

// ParseHTTPCredentials bounds and freezes only the credential candidates.
// It grants no authority and never includes private input in a returned error.
func ParseHTTPCredentials(ctx context.Context, transport, interfaceID string, headers http.Header) (HTTPCredentials, error) {
	if ctx == nil || (transport != "connect" && transport != "rest") {
		return HTTPCredentials{}, ErrInvalidHTTPCredentials
	}
	id, err := capability.ParseIdentifier(interfaceID)
	if err != nil || id.String() != interfaceID {
		return HTTPCredentials{}, ErrInvalidHTTPCredentials
	}
	if _, present, err := contextmetadata.Bytes(ctx, httpCredentialsKey); err != nil || present {
		return HTTPCredentials{}, ErrInvalidHTTPCredentials
	}
	type cookie struct { Name string ` + "`json:\"name\"`" + `; Value string ` + "`json:\"value\"`" + ` }
	input := struct {
		Transport string ` + "`json:\"transport\"`" + `
		InterfaceID string ` + "`json:\"interface_id\"`" + `
		Bearer string ` + "`json:\"bearer,omitempty\"`" + `
		Cookies []cookie ` + "`json:\"cookies\"`" + `
	}{Transport: transport, InterfaceID: interfaceID, Cookies: make([]cookie, 0)}
	authorizations, cookieCount, cookieBytes := 0, 0, 0
	names := make(map[string]bool)
	for key, values := range headers {
		switch {
		case strings.EqualFold(key, "Authorization"):
			if len(values) != 1 || authorizations != 0 {
				return HTTPCredentials{}, ErrInvalidHTTPCredentials
			}
			authorizations++
			value := values[0]
			scheme, bearer, found := strings.Cut(value, " ")
			bearer = strings.TrimLeft(bearer, " ")
			if !found || !strings.EqualFold(scheme, "Bearer") || len(bearer) == 0 || len(bearer) > 65536 {
				return HTTPCredentials{}, ErrInvalidHTTPCredentials
			}
			for index := 0; index < len(bearer); index++ {
				if bearer[index] < 0x21 || bearer[index] > 0x7e {
					return HTTPCredentials{}, ErrInvalidHTTPCredentials
				}
			}
			input.Bearer = bearer
		case strings.EqualFold(key, "Cookie"):
			if len(values) == 0 || len(values) > 32-cookieCount {
				return HTTPCredentials{}, ErrInvalidHTTPCredentials
			}
			for _, line := range values {
				// Bound work before ParseCookie allocates a split for every pair.
				if strings.Count(line, ";") + 1 > 32-cookieCount {
					return HTTPCredentials{}, ErrInvalidHTTPCredentials
				}
				for index := 0; index < len(line); index++ {
					if (line[index] < 0x20 && line[index] != '\t') || line[index] > 0x7e {
						return HTTPCredentials{}, ErrInvalidHTTPCredentials
					}
				}
				parsed, err := http.ParseCookie(line)
				if err != nil { return HTTPCredentials{}, ErrInvalidHTTPCredentials }
				for _, pair := range parsed {
					if len(pair.Name) > 256 || len(pair.Value) > 4096 || names[pair.Name] {
						return HTTPCredentials{}, ErrInvalidHTTPCredentials
					}
					cookieCount++
					cookieBytes += len(pair.Name) + len(pair.Value)
					if cookieBytes > 65536 { return HTTPCredentials{}, ErrInvalidHTTPCredentials }
					names[pair.Name] = true
					input.Cookies = append(input.Cookies, cookie{Name: pair.Name, Value: pair.Value})
				}
			}
		}
	}
	sort.Slice(input.Cookies, func(i, j int) bool { return input.Cookies[i].Name < input.Cookies[j].Name })
	payload, err := json.Marshal(input)
	if err != nil || len(payload) > 262144 { return HTTPCredentials{}, ErrInvalidHTTPCredentials }
	return HTTPCredentials{payload: payload}, nil
}

// WithContext attaches a defensive copy after the trusted request root exists.
// Existing metadata is a conflict, including when that root detached from ingress.
func (c HTTPCredentials) WithContext(ctx context.Context) (context.Context, error) {
	if len(c.payload) == 0 { return nil, ErrInvalidHTTPCredentials }
	result, err := contextmetadata.WithBytes(ctx, httpCredentialsKey, c.payload)
	if err != nil { return nil, ErrInvalidHTTPCredentials }
	return result, nil
}
`
