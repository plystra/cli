func renderInterfaceEncodeField(source *strings.Builder, index int, prepared preparedInterfaceField) {
	fieldName := fmt.Sprintf("field%d", index)
	value := "value." + prepared.field.GoName()
	fieldType := prepared.field.Type()
	fmt.Fprintf(source, "\t%s, err := connectschema.Field(reflected, %d, %s)\n", fieldName, prepared.wire.Number(), strconv.Quote(prepared.wire.Name()))
	fmt.Fprintln(source, "\tif err != nil {")
	fmt.Fprintln(source, "\t\treturn nil, plystraErrInvalidResponse")
	fmt.Fprintln(source, "\t}")
	if interfaceNilable(fieldType) {
		if prepared.field.Required() {
			fmt.Fprintf(source, "\tif %s == nil {\n", value)
			fmt.Fprintln(source, "\t\treturn nil, plystraErrInvalidResponse")
			fmt.Fprintln(source, "\t}")
		} else {
			fmt.Fprintf(source, "\tif %s != nil {\n", value)
		}
	}
	indent := "\t"
	if interfaceNilable(fieldType) && !prepared.field.Required() {
		indent = "\t\t"
	}
	fmt.Fprintf(source, "%sif budget.ConsumeNodes(1) != nil {\n", indent)
	fmt.Fprintf(source, "%s\treturn nil, plystraErrInvalidResponse\n", indent)
	fmt.Fprintf(source, "%s}\n", indent)
	switch fieldType.Kind() {
	case interfacecontract.TypeRepeated:
		element, _ := fieldType.Element()
		list := fmt.Sprintf("list%d", index)
		fmt.Fprintf(source, "%sif budget.ConsumeNodes(len(%s)) != nil {\n", indent, value)
		fmt.Fprintf(source, "%s\treturn nil, plystraErrInvalidResponse\n", indent)
		fmt.Fprintf(source, "%s}\n", indent)
		fmt.Fprintf(source, "%s%s := reflected.Mutable(%s).List()\n", indent, list, fieldName)
		fmt.Fprintf(source, "%sfor _, item := range %s {\n", indent, value)
		renderInterfaceEncodeValue(source, indent+"\t", list+".Append", "item", element, fieldName+".Message()", fmt.Sprintf("%dItem", index))
		fmt.Fprintf(source, "%s}\n", indent)
	case interfacecontract.TypeMap:
		keyType, _ := fieldType.Key()
		valueType, _ := fieldType.Value()
		values := fmt.Sprintf("values%d", index)
		fmt.Fprintf(source, "%sif budget.ConsumeNodes(len(%s)) != nil {\n", indent, value)
		fmt.Fprintf(source, "%s\treturn nil, plystraErrInvalidResponse\n", indent)
		fmt.Fprintf(source, "%s}\n", indent)
		fmt.Fprintf(source, "%s%s := reflected.Mutable(%s).Map()\n", indent, values, fieldName)
		fmt.Fprintf(source, "%sfor key, item := range %s {\n", indent, value)
		if keyType.Kind() == interfacecontract.TypeString {
			fmt.Fprintf(source, "%s\tif !utf8.ValidString(key) || budget.ConsumeBytes(len(key)) != nil {\n", indent)
			fmt.Fprintf(source, "%s\t\treturn nil, plystraErrInvalidResponse\n", indent)
			fmt.Fprintf(source, "%s\t}\n", indent)
		}
		fmt.Fprintf(source, "%s\tencodedKey := %s.MapKey()\n", indent, interfaceEncodeScalar(keyType, "key"))
		renderInterfaceEncodeMapValue(source, indent+"\t", values, "encodedKey", "item", valueType, fieldName+".MapValue().Message()", fmt.Sprintf("%dMap", index))
		fmt.Fprintf(source, "%s}\n", indent)
	default:
		renderInterfaceEncodeValue(source, indent, "reflected.Set", value, fieldType, fieldName+".Message()", strconv.Itoa(index), fieldName)
	}
	if interfaceNilable(fieldType) && !prepared.field.Required() {
		fmt.Fprintln(source, "\t}")
	}
}

