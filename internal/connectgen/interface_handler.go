func interfaceOperationUsesKind(operation protobufmodel.InterfaceOperation, kind interfacecontract.TypeKind) bool {
	for _, message := range operation.Messages() {
		for _, field := range message.Fields() {
			if interfaceTypeUsesKind(field.Type(), kind) {
				return true
			}
		}
	}
	return false
}

func interfaceTypeUsesKind(fieldType interfacecontract.Type, kind interfacecontract.TypeKind) bool {
	if fieldType.Kind() == kind {
		return true
	}
	switch fieldType.Kind() {
	case interfacecontract.TypeRepeated:
		element, _ := fieldType.Element()
		return interfaceTypeUsesKind(element, kind)
	case interfacecontract.TypeMap:
		key, _ := fieldType.Key()
		value, _ := fieldType.Value()
		return interfaceTypeUsesKind(key, kind) || interfaceTypeUsesKind(value, kind)
	default:
		return false
	}
}

func interfaceCollection(fieldType interfacecontract.Type) bool {
	return fieldType.Kind() == interfacecontract.TypeRepeated || fieldType.Kind() == interfacecontract.TypeMap
}

func interfaceNilable(fieldType interfacecontract.Type) bool {
	return interfaceCollection(fieldType) || fieldType.Kind() == interfacecontract.TypeBytes
}

