package connectgen

import (
	"crypto/sha256"
	"encoding/hex"
	"fmt"
	"go/format"
	"strconv"
	"strings"
)

func renderSchemaRuntime(descriptorSet []byte) ([]byte, error) {
	if len(descriptorSet) == 0 {
		return nil, fmt.Errorf("%w: descriptor set is empty", ErrDescriptor)
	}
	digest := sha256.Sum256(descriptorSet)
	var source strings.Builder
	fmt.Fprintln(&source, "// Code generated by Plystra CLI. DO NOT EDIT.")
	fmt.Fprintln(&source)
	fmt.Fprintln(&source, "// Package connectschema owns the immutable descriptor graph shared by generated Connect handlers.")
	fmt.Fprintln(&source, "package connectschema")
	fmt.Fprintln(&source)
	fmt.Fprintln(&source, "import (")
	fmt.Fprintln(&source, "\t\"errors\"")
	fmt.Fprintln(&source, "\t\"fmt\"")
	fmt.Fprintln(&source, "\t\"sync\"")
	fmt.Fprintln(&source)
	fmt.Fprintln(&source, "\t\"connectrpc.com/connect\"")
	fmt.Fprintln(&source, "\t\"google.golang.org/protobuf/proto\"")
	fmt.Fprintln(&source, "\t\"google.golang.org/protobuf/reflect/protodesc\"")
	fmt.Fprintln(&source, "\t\"google.golang.org/protobuf/reflect/protoreflect\"")
	fmt.Fprintln(&source, "\t\"google.golang.org/protobuf/reflect/protoregistry\"")
	fmt.Fprintln(&source, "\t\"google.golang.org/protobuf/types/descriptorpb\"")
	fmt.Fprintln(&source, "\t\"google.golang.org/protobuf/types/dynamicpb\"")
	fmt.Fprintln(&source, "\t\"google.golang.org/protobuf/types/known/structpb\"")
	fmt.Fprintln(&source, ")")
	fmt.Fprintln(&source)
	fmt.Fprintf(&source, "const DescriptorSetDigest = %s\n", strconv.Quote("sha256:"+hex.EncodeToString(digest[:])))
	fmt.Fprintf(&source, "const plystraDescriptorSet = %s\n", strconv.Quote(string(descriptorSet)))
	fmt.Fprintln(&source)
	fmt.Fprintln(&source, "var (")
	fmt.Fprintln(&source, "\tErrInvalidSchema = errors.New(\"invalid generated Connect schema\")")
	fmt.Fprintln(&source, "\tplystraFilesOnce sync.Once")
	fmt.Fprintln(&source, "\tplystraFiles *protoregistry.Files")
	fmt.Fprintln(&source, "\tplystraFilesError error")
	fmt.Fprintln(&source, ")")
	fmt.Fprintln(&source)
	fmt.Fprintln(&source, "// Method returns one exact generated unary method descriptor by full name.")
	fmt.Fprintln(&source, "func Method(name protoreflect.FullName) (protoreflect.MethodDescriptor, error) {")
	fmt.Fprintln(&source, "\tplystraFilesOnce.Do(func() {")
	fmt.Fprintln(&source, "\t\tvar set descriptorpb.FileDescriptorSet")
	fmt.Fprintln(&source, "\t\tif err := (proto.UnmarshalOptions{DiscardUnknown: false}).Unmarshal([]byte(plystraDescriptorSet), &set); err != nil {")
	fmt.Fprintln(&source, "\t\t\tplystraFilesError = fmt.Errorf(\"%w: decode descriptor set\", ErrInvalidSchema)")
	fmt.Fprintln(&source, "\t\t\treturn")
	fmt.Fprintln(&source, "\t\t}")
	fmt.Fprintln(&source, "\t\tfiles, err := protodesc.NewFiles(&set)")
	fmt.Fprintln(&source, "\t\tif err != nil {")
	fmt.Fprintln(&source, "\t\t\tplystraFilesError = fmt.Errorf(\"%w: construct descriptor graph\", ErrInvalidSchema)")
	fmt.Fprintln(&source, "\t\t\treturn")
	fmt.Fprintln(&source, "\t\t}")
	fmt.Fprintln(&source, "\t\tplystraFiles = files")
	fmt.Fprintln(&source, "\t})")
	fmt.Fprintln(&source, "\tif plystraFilesError != nil {")
	fmt.Fprintln(&source, "\t\treturn nil, plystraFilesError")
	fmt.Fprintln(&source, "\t}")
	fmt.Fprintln(&source, "\tif plystraFiles == nil || !name.IsValid() {")
	fmt.Fprintln(&source, "\t\treturn nil, fmt.Errorf(\"%w: method name is invalid\", ErrInvalidSchema)")
	fmt.Fprintln(&source, "\t}")
	fmt.Fprintln(&source, "\tdescriptor, err := plystraFiles.FindDescriptorByName(name)")
	fmt.Fprintln(&source, "\tif err != nil {")
	source.WriteString("\t\treturn nil, fmt.Errorf(\"%w: method %s is absent\", ErrInvalidSchema, name)\n")
	fmt.Fprintln(&source, "\t}")
	fmt.Fprintln(&source, "\tmethod, ok := descriptor.(protoreflect.MethodDescriptor)")
	fmt.Fprintln(&source, "\tif !ok || method == nil || method.IsStreamingClient() || method.IsStreamingServer() {")
	source.WriteString("\t\treturn nil, fmt.Errorf(\"%w: descriptor %s is not unary\", ErrInvalidSchema, name)\n")
	fmt.Fprintln(&source, "\t}")
	fmt.Fprintln(&source, "\treturn method, nil")
	fmt.Fprintln(&source, "}")
	fmt.Fprintln(&source)
	fmt.Fprintln(&source, "// InitializeDynamicMessage binds Connect's generic message allocation to the exact method schema.")
	fmt.Fprintln(&source, "func InitializeDynamicMessage(spec connect.Spec, message any) error {")
	fmt.Fprintln(&source, "\tdynamic, ok := message.(*dynamicpb.Message)")
	fmt.Fprintln(&source, "\tif !ok || dynamic == nil {")
	fmt.Fprintln(&source, "\t\treturn fmt.Errorf(\"%w: message type is invalid\", ErrInvalidSchema)")
	fmt.Fprintln(&source, "\t}")
	fmt.Fprintln(&source, "\tmethod, ok := spec.Schema.(protoreflect.MethodDescriptor)")
	fmt.Fprintln(&source, "\tif !ok || method == nil {")
	fmt.Fprintln(&source, "\t\treturn fmt.Errorf(\"%w: method schema is absent\", ErrInvalidSchema)")
	fmt.Fprintln(&source, "\t}")
	fmt.Fprintln(&source, "\tdescriptor := method.Input()")
	fmt.Fprintln(&source, "\tif spec.IsClient {")
	fmt.Fprintln(&source, "\t\tdescriptor = method.Output()")
	fmt.Fprintln(&source, "\t}")
	fmt.Fprintln(&source, "\tif descriptor == nil {")
	fmt.Fprintln(&source, "\t\treturn fmt.Errorf(\"%w: message descriptor is absent\", ErrInvalidSchema)")
	fmt.Fprintln(&source, "\t}")
	fmt.Fprintln(&source, "\t*dynamic = *dynamicpb.NewMessage(descriptor)")
	fmt.Fprintln(&source, "\treturn nil")
	fmt.Fprintln(&source, "}")
	fmt.Fprintln(&source)
	fmt.Fprintln(&source, "// Field returns one exact generated field assignment from a validated message.")
	fmt.Fprintln(&source, "func Field(message protoreflect.Message, number protoreflect.FieldNumber, name protoreflect.Name) (protoreflect.FieldDescriptor, error) {")
	fmt.Fprintln(&source, "\tif !message.IsValid() || number <= 0 || !name.IsValid() {")
	fmt.Fprintln(&source, "\t\treturn nil, fmt.Errorf(\"%w: field identity is invalid\", ErrInvalidSchema)")
	fmt.Fprintln(&source, "\t}")
	fmt.Fprintln(&source, "\tfield := message.Descriptor().Fields().ByNumber(number)")
	fmt.Fprintln(&source, "\tif field == nil || field.Name() != name {")
	source.WriteString("\t\treturn nil, fmt.Errorf(\"%w: field %d does not match %s\", ErrInvalidSchema, number, name)\n")
	fmt.Fprintln(&source, "\t}")
	fmt.Fprintln(&source, "\treturn field, nil")
	fmt.Fprintln(&source, "}")
	fmt.Fprintln(&source)
	fmt.Fprintln(&source, "// DecodeStruct converts one generated google.protobuf.Struct value without using JSON as an in-process bridge.")
	fmt.Fprintln(&source, "func DecodeStruct(message protoreflect.Message) (map[string]any, error) {")
	fmt.Fprintln(&source, "\tif !message.IsValid() || message.Descriptor().FullName() != \"google.protobuf.Struct\" {")
	fmt.Fprintln(&source, "\t\treturn nil, fmt.Errorf(\"%w: object message is invalid\", ErrInvalidSchema)")
	fmt.Fprintln(&source, "\t}")
	fmt.Fprintln(&source, "\tdata, err := (proto.MarshalOptions{Deterministic: true}).Marshal(message.Interface())")
	fmt.Fprintln(&source, "\tif err != nil {")
	fmt.Fprintln(&source, "\t\treturn nil, fmt.Errorf(\"%w: encode object message\", ErrInvalidSchema)")
	fmt.Fprintln(&source, "\t}")
	fmt.Fprintln(&source, "\tvar value structpb.Struct")
	fmt.Fprintln(&source, "\tif err := (proto.UnmarshalOptions{DiscardUnknown: false}).Unmarshal(data, &value); err != nil || len(value.ProtoReflect().GetUnknown()) != 0 {")
	fmt.Fprintln(&source, "\t\treturn nil, fmt.Errorf(\"%w: decode object message\", ErrInvalidSchema)")
	fmt.Fprintln(&source, "\t}")
	fmt.Fprintln(&source, "\treturn value.AsMap(), nil")
	fmt.Fprintln(&source, "}")
	fmt.Fprintln(&source)
	fmt.Fprintln(&source, "// EncodeStruct converts one canonical object into the exact generated Struct descriptor.")
	fmt.Fprintln(&source, "func EncodeStruct(descriptor protoreflect.MessageDescriptor, value map[string]any) (protoreflect.Message, error) {")
	fmt.Fprintln(&source, "\tif descriptor == nil || descriptor.FullName() != \"google.protobuf.Struct\" || value == nil {")
	fmt.Fprintln(&source, "\t\treturn nil, fmt.Errorf(\"%w: canonical object is invalid\", ErrInvalidSchema)")
	fmt.Fprintln(&source, "\t}")
	fmt.Fprintln(&source, "\tstructured, err := structpb.NewStruct(value)")
	fmt.Fprintln(&source, "\tif err != nil {")
	fmt.Fprintln(&source, "\t\treturn nil, fmt.Errorf(\"%w: canonical object value is invalid\", ErrInvalidSchema)")
	fmt.Fprintln(&source, "\t}")
	fmt.Fprintln(&source, "\tdata, err := (proto.MarshalOptions{Deterministic: true}).Marshal(structured)")
	fmt.Fprintln(&source, "\tif err != nil {")
	fmt.Fprintln(&source, "\t\treturn nil, fmt.Errorf(\"%w: encode canonical object\", ErrInvalidSchema)")
	fmt.Fprintln(&source, "\t}")
	fmt.Fprintln(&source, "\tdynamic := dynamicpb.NewMessage(descriptor)")
	fmt.Fprintln(&source, "\tif err := (proto.UnmarshalOptions{DiscardUnknown: false}).Unmarshal(data, dynamic); err != nil || len(dynamic.GetUnknown()) != 0 {")
	fmt.Fprintln(&source, "\t\treturn nil, fmt.Errorf(\"%w: project canonical object\", ErrInvalidSchema)")
	fmt.Fprintln(&source, "\t}")
	fmt.Fprintln(&source, "\treturn dynamic.ProtoReflect(), nil")
	fmt.Fprintln(&source, "}")

	formatted, err := format.Source([]byte(source.String()))
	if err != nil {
		return nil, fmt.Errorf("format generated descriptor runtime: %w", err)
	}
	return append([]byte(nil), formatted...), nil
}
