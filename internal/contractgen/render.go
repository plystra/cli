// Package contractgen renders deterministic Go request, response, enum, and
// semantic error types from one capability declaration.
package contractgen

import (
	"crypto/sha256"
	"encoding/json"
	"errors"
	"fmt"
	"go/format"
	"go/token"
	"path"
	"sort"
	"strconv"
	"strings"

	"github.com/plystra/cli/internal/capabilityid"
	"github.com/plystra/cli/internal/capabilitymeta"
	"github.com/plystra/cli/internal/goname"
	kernelcatalog "github.com/plystra/kernel/capability/catalog"
)

var (
	// ErrRender reports that a capability declaration could not produce a Go
	// contract file.
	ErrRender = errors.New("render Go capability contract")
	// ErrNameCollision reports distinct wire names that map to one Go name.
	ErrNameCollision = errors.New("generated Go name collision")
)

// File is one immutable generated Go contract output.
type File struct {
	path        string
	packageName string
	data        []byte
}

// Path returns the slash-separated module-relative generated file path.
func (f File) Path() string { return f.path }

// PackageName returns the generated Go package identifier.
func (f File) PackageName() string { return f.packageName }

// Data returns a defensive copy of the formatted generated source.
func (f File) Data() []byte { return append([]byte(nil), f.data...) }

type canonicalContract struct {
	ID       string                    `json:"id"`
	Request  map[string]canonicalField `json:"request"`
	Response map[string]canonicalField `json:"response"`
	Errors   []string                  `json:"errors"`
}

type canonicalField struct {
	Type     string            `json:"type"`
	Items    string            `json:"items,omitempty"`
	Required bool              `json:"required,omitempty"`
	Enum     []json.RawMessage `json:"enum,omitempty"`
}

type generatedField struct {
	wireName string
	goName   string
	typeName string
	required bool
	enum     *generatedEnum
}

type generatedEnum struct {
	name       string
	underlying string
	values     []generatedEnumValue
}

type generatedEnumValue struct {
	name    string
	literal string
}

// Render validates schema, derives its stable generated location, and returns
// gofmt-formatted source. Optional fields use pointers so absent values remain
// distinguishable from explicit zero, empty, or false values.
func Render(schema []byte) (File, error) {
	return render(schema, false)
}

// RenderIntrinsic emits aliases to the Kernel-owned request, response, and
// enum types for one exact intrinsic contract. It never declares a parallel
// application-owned intrinsic type model.
func RenderIntrinsic(schema []byte) (File, error) {
	return render(schema, true)
}

func render(schema []byte, intrinsic bool) (File, error) {
	canonical, err := capabilitymeta.NormalizeSchema(schema)
	if err != nil {
		return File{}, fmt.Errorf("%w: normalize schema: %w", ErrRender, err)
	}
	var contract canonicalContract
	if err := json.Unmarshal(canonical, &contract); err != nil {
		return File{}, fmt.Errorf("%w: decode canonical schema: %w", ErrRender, err)
	}
	identifier, err := capabilityid.Parse(contract.ID)
	if err != nil {
		return File{}, fmt.Errorf("%w: decode canonical identity: %w", ErrRender, err)
	}
	reservedIntrinsic := strings.HasPrefix(identifier.Name(), "kernel.")
	if intrinsic && !reservedIntrinsic {
		return File{}, fmt.Errorf("%w: Capability %s does not use the reserved kernel.* namespace", ErrRender, identifier)
	}
	if intrinsic {
		if err := validateIntrinsicSchema(identifier, canonical); err != nil {
			return File{}, fmt.Errorf("%w: %w", ErrRender, err)
		}
	}
	request, err := prepareFields("Request", contract.Request)
	if err != nil {
		return File{}, fmt.Errorf("%w: %w", ErrRender, err)
	}
	response, err := prepareFields("Response", contract.Response)
	if err != nil {
		return File{}, fmt.Errorf("%w: %w", ErrRender, err)
	}
	errorNames, err := prepareErrorNames(contract.Errors)
	if err != nil {
		return File{}, fmt.Errorf("%w: %w", ErrRender, err)
	}

	packageName := goname.Package(identifier)
	if !token.IsIdentifier(packageName) || token.Lookup(packageName).IsKeyword() {
		return File{}, fmt.Errorf("%w: generated package %q is invalid", ErrRender, packageName)
	}
	var source strings.Builder
	fmt.Fprintln(&source, "// Code generated by Plystra CLI. DO NOT EDIT.")
	fmt.Fprintln(&source)
	fmt.Fprintf(&source, "package %s\n\n", packageName)
	if intrinsic {
		fmt.Fprintln(&source, "import kernelintrinsic \"github.com/plystra/kernel/intrinsic\"")
		fmt.Fprintln(&source)
	}
	fmt.Fprintf(&source, "const CapabilityID = %s\n\n", strconv.Quote(identifier.String()))
	if intrinsic {
		renderIntrinsicTypes(&source, identifier)
	} else {
		renderEnums(&source, request)
		renderEnums(&source, response)
		renderStruct(&source, "Request", request)
		renderStruct(&source, "Response", response)
	}
	renderErrors(&source, contract.Errors, errorNames)
	formatted, err := format.Source([]byte(source.String()))
	if err != nil {
		return File{}, fmt.Errorf("%w: format generated source: %w", ErrRender, err)
	}
	return File{
		path:        generatedPath(identifier),
		packageName: packageName,
		data:        append([]byte(nil), formatted...),
	}, nil
}

func validateIntrinsicSchema(identifier capabilityid.Identifier, canonical []byte) error {
	digest := sha256.Sum256(canonical)
	for _, definition := range kernelcatalog.Definitions() {
		if definition.ID().String() != identifier.String() {
			continue
		}
		if definition.SchemaDigest() != digest {
			return fmt.Errorf("intrinsic Capability %s differs from the Kernel catalog", identifier)
		}
		switch identifier.String() {
		case "kernel.health/v1", "kernel.info/v1":
			return nil
		default:
			return fmt.Errorf("intrinsic Capability %s has no supported generated type aliases", identifier)
		}
	}
	return fmt.Errorf("intrinsic Capability %s is absent from the Kernel catalog", identifier)
}

func renderIntrinsicTypes(source *strings.Builder, identifier capabilityid.Identifier) {
	switch identifier.String() {
	case "kernel.health/v1":
		fmt.Fprintln(source, "type Request = kernelintrinsic.HealthRequest")
		fmt.Fprintln(source)
		fmt.Fprintln(source, "type Response = kernelintrinsic.HealthResponse")
		fmt.Fprintln(source)
		fmt.Fprintln(source, "type ResponseStatus = kernelintrinsic.HealthStatus")
		fmt.Fprintln(source)
		fmt.Fprintln(source, "const ResponseStatusHealthy ResponseStatus = kernelintrinsic.HealthStatusHealthy")
		fmt.Fprintln(source)
	case "kernel.info/v1":
		fmt.Fprintln(source, "type Request = kernelintrinsic.InfoRequest")
		fmt.Fprintln(source)
		fmt.Fprintln(source, "type Response = kernelintrinsic.InfoResponse")
		fmt.Fprintln(source)
	}
}

func prepareFields(section string, fields map[string]canonicalField) ([]generatedField, error) {
	wireNames := make([]string, 0, len(fields))
	for name := range fields {
		wireNames = append(wireNames, name)
	}
	sort.Strings(wireNames)
	result := make([]generatedField, 0, len(wireNames))
	goNames := make(map[string]string, len(wireNames))
	for _, wireName := range wireNames {
		field := fields[wireName]
		goName := exportedName(wireName)
		if previous, duplicate := goNames[goName]; duplicate {
			return nil, fmt.Errorf("%w: %s fields %q and %q both map to %s", ErrNameCollision, strings.ToLower(section), previous, wireName, goName)
		}
		goNames[goName] = wireName
		var typeName string
		var err error
		if field.Type == "array" {
			itemType, itemErr := goType(field.Items)
			if itemErr != nil {
				return nil, itemErr
			}
			typeName = "[]" + itemType
		} else {
			typeName, err = goType(field.Type)
			if err != nil {
				return nil, err
			}
		}
		generated := generatedField{wireName: wireName, goName: goName, typeName: typeName, required: field.Required}
		if len(field.Enum) != 0 {
			enum, err := prepareEnum(section+goName, field.Type, field.Enum)
			if err != nil {
				return nil, err
			}
			generated.typeName = enum.name
			generated.enum = &enum
		}
		result = append(result, generated)
	}
	return result, nil
}

func prepareEnum(name, schemaType string, values []json.RawMessage) (generatedEnum, error) {
	underlying, err := goType(schemaType)
	if err != nil {
		return generatedEnum{}, err
	}
	result := generatedEnum{name: name, underlying: underlying, values: make([]generatedEnumValue, 0, len(values))}
	used := make(map[string]struct{}, len(values))
	for index, raw := range values {
		literal, err := enumLiteral(schemaType, raw)
		if err != nil {
			return generatedEnum{}, err
		}
		suffix := enumSuffix(schemaType, raw, index)
		constantName := name + suffix
		if _, duplicate := used[constantName]; duplicate || !token.IsIdentifier(constantName) {
			for serial := index + 1; ; serial++ {
				candidate := name + "Value" + strconv.Itoa(serial)
				if _, duplicate := used[candidate]; !duplicate {
					constantName = candidate
					break
				}
			}
		}
		used[constantName] = struct{}{}
		result.values = append(result.values, generatedEnumValue{name: constantName, literal: literal})
	}
	return result, nil
}

func enumLiteral(schemaType string, raw json.RawMessage) (string, error) {
	if schemaType != "string" {
		return string(raw), nil
	}
	var value string
	if err := json.Unmarshal(raw, &value); err != nil {
		return "", fmt.Errorf("decode string enum: %w", err)
	}
	return strconv.Quote(value), nil
}

func enumSuffix(schemaType string, raw json.RawMessage, index int) string {
	var value string
	switch schemaType {
	case "string":
		if err := json.Unmarshal(raw, &value); err != nil {
			return "Value" + strconv.Itoa(index+1)
		}
		value = exportedEnumValue(value)
	case "boolean":
		value = strings.ToUpper(string(raw[:1])) + string(raw[1:])
	case "integer", "number":
		value = strings.NewReplacer("-", "Negative", "+", "Plus", ".", "Point", "e", "Exponent", "E", "Exponent").Replace(string(raw))
	}
	if value == "" {
		return "Value" + strconv.Itoa(index+1)
	}
	return value
}

func exportedEnumValue(value string) string {
	parts := strings.FieldsFunc(value, func(character rune) bool {
		return character < '0' || character > '9' && character < 'A' || character > 'Z' && character < 'a' || character > 'z'
	})
	if len(parts) == 0 {
		return ""
	}
	for index := range parts {
		parts[index] = exportedWord(parts[index])
	}
	return strings.Join(parts, "")
}

func prepareErrorNames(codes []string) ([]string, error) {
	result := make([]string, len(codes))
	used := make(map[string]string, len(codes))
	for index, code := range codes {
		name := "Err" + exportedName(code)
		if previous, duplicate := used[name]; duplicate {
			return nil, fmt.Errorf("%w: error codes %q and %q both map to %s", ErrNameCollision, previous, code, name)
		}
		used[name] = code
		result[index] = name
	}
	return result, nil
}

func renderEnums(source *strings.Builder, fields []generatedField) {
	for _, field := range fields {
		if field.enum == nil {
			continue
		}
		fmt.Fprintf(source, "type %s %s\n\n", field.enum.name, field.enum.underlying)
		fmt.Fprintln(source, "const (")
		for _, value := range field.enum.values {
			fmt.Fprintf(source, "\t%s %s = %s\n", value.name, field.enum.name, value.literal)
		}
		fmt.Fprintln(source, ")")
		fmt.Fprintln(source)
	}
}

func renderStruct(source *strings.Builder, name string, fields []generatedField) {
	if len(fields) == 0 {
		fmt.Fprintf(source, "type %s struct{}\n\n", name)
		return
	}
	fmt.Fprintf(source, "type %s struct {\n", name)
	for _, field := range fields {
		typeName := field.typeName
		tag := field.wireName
		if !field.required {
			typeName = "*" + typeName
			tag += ",omitempty"
		}
		fmt.Fprintf(source, "\t%s %s `json:%s`\n", field.goName, typeName, strconv.Quote(tag))
	}
	fmt.Fprintln(source, "}")
	fmt.Fprintln(source)
}

func renderErrors(source *strings.Builder, codes, names []string) {
	fmt.Fprintln(source, "type ErrorCode string")
	fmt.Fprintln(source)
	if len(codes) != 0 {
		fmt.Fprintln(source, "const (")
		for index, code := range codes {
			fmt.Fprintf(source, "\t%s ErrorCode = %s\n", names[index], strconv.Quote(code))
		}
		fmt.Fprintln(source, ")")
		fmt.Fprintln(source)
	}
	fmt.Fprintln(source, "func (c ErrorCode) Error() string {")
	fmt.Fprintln(source, "\treturn string(c)")
	fmt.Fprintln(source, "}")
	fmt.Fprintln(source)
	fmt.Fprintln(source, "func (c ErrorCode) SemanticErrorCode() string {")
	fmt.Fprintln(source, "\treturn string(c)")
	fmt.Fprintln(source, "}")
}

func goType(schemaType string) (string, error) {
	switch schemaType {
	case "string":
		return "string", nil
	case "integer":
		return "int64", nil
	case "number":
		return "float64", nil
	case "boolean":
		return "bool", nil
	case "object":
		return "map[string]any", nil
	default:
		return "", fmt.Errorf("unsupported canonical schema type %q", schemaType)
	}
}

func exportedName(value string) string {
	return goname.Field(value)
}

func exportedWord(value string) string {
	return goname.ExportedWord(value)
}

func generatedPath(identifier capabilityid.Identifier) string {
	components := append([]string{"generated", "go", "contracts"}, strings.Split(identifier.Name(), ".")...)
	components = append(components, "v"+strconv.FormatUint(identifier.Major(), 10), "contract_gen.go")
	return path.Join(components...)
}
