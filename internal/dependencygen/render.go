// Package dependencygen renders immutable typed Capability-client sets for
// plugin constructors.
package dependencygen

import (
	"errors"
	"fmt"
	"go/format"
	"path"
	"sort"
	"strconv"
	"strings"

	"github.com/plystra/cli/internal/capabilityid"
	"github.com/plystra/cli/internal/configurationgen"
	"github.com/plystra/cli/internal/goname"
	"github.com/plystra/cli/internal/pluginid"
	"golang.org/x/mod/module"
)

var (
	// ErrRender reports invalid plugin dependency input or a generated source
	// formatting failure.
	ErrRender = errors.New("render plugin Capability dependencies")
	// ErrInvalidInput reports incomplete or contradictory plugin dependency
	// provenance.
	ErrInvalidInput = errors.New("invalid plugin Capability dependencies")
	// ErrIdentifierCollision reports two exact Capability IDs that produce one
	// Go accessor.
	ErrIdentifierCollision = errors.New("plugin dependency Go identifier collision")
)

// File is one immutable generated dependency source file.
type File struct {
	path string
	data []byte
}

// Path returns the slash-separated module-relative generated file path.
func (f File) Path() string { return f.path }

// Data returns a defensive copy of the formatted generated source.
func (f File) Data() []byte { return append([]byte(nil), f.data...) }

type requirement struct {
	id       capabilityid.Identifier
	accessor string
	alias    string
}

// Render emits one plugin-specific immutable set of exact generated clients.
// Requirements are sorted by canonical identity, never by declaration order.
func Render(modulePath, pluginName, pluginID string, required []string) (File, error) {
	if err := module.CheckPath(modulePath); err != nil {
		return File{}, fmt.Errorf("%w: %w: invalid Go Module path %q: %v", ErrRender, ErrInvalidInput, modulePath, err)
	}
	if _, err := configurationgen.DeriveGoNames(pluginName); err != nil {
		return File{}, fmt.Errorf("%w: %w: %v", ErrRender, ErrInvalidInput, err)
	}
	if err := pluginid.Validate(pluginID); err != nil {
		return File{}, fmt.Errorf("%w: %w: Plugin ID %q: %v", ErrRender, ErrInvalidInput, pluginID, err)
	}
	if len(required) == 0 {
		return File{}, fmt.Errorf("%w: %w: plugin %q has no required Capabilities", ErrRender, ErrInvalidInput, pluginID)
	}

	requirements := make([]requirement, len(required))
	seen := make(map[capabilityid.Identifier]struct{}, len(required))
	accessors := make(map[string]capabilityid.Identifier, len(required))
	for index, value := range required {
		identifier, err := capabilityid.Parse(value)
		if err != nil {
			return File{}, fmt.Errorf("%w: %w: plugin %q requirement %q: %v", ErrRender, ErrInvalidInput, pluginID, value, err)
		}
		if _, duplicate := seen[identifier]; duplicate {
			return File{}, fmt.Errorf("%w: %w: plugin %q duplicates %s", ErrRender, ErrInvalidInput, pluginID, identifier)
		}
		seen[identifier] = struct{}{}
		accessor := capabilityAccessor(identifier)
		if previous, collision := accessors[accessor]; collision {
			return File{}, fmt.Errorf("%w: %w: plugin %q requirements %s and %s both generate %s", ErrRender, ErrIdentifierCollision, pluginID, previous, identifier, accessor)
		}
		accessors[accessor] = identifier
		requirements[index] = requirement{id: identifier, accessor: accessor}
	}
	sort.Slice(requirements, func(left, right int) bool {
		return requirements[left].id.String() < requirements[right].id.String()
	})
	for index := range requirements {
		requirements[index].alias = fmt.Sprintf("client%d", index)
	}

	var source strings.Builder
	fmt.Fprintln(&source, "// Code generated by Plystra CLI. DO NOT EDIT.")
	fmt.Fprintln(&source)
	fmt.Fprintln(&source, "package dependencies")
	fmt.Fprintln(&source)
	fmt.Fprintln(&source, "import (")
	fmt.Fprintln(&source, "\t\"errors\"")
	for _, dependency := range requirements {
		fmt.Fprintf(&source, "\t%s %s\n", dependency.alias, strconv.Quote(clientImportPath(modulePath, dependency.id)))
	}
	fmt.Fprintln(&source, ")")
	fmt.Fprintln(&source)
	fmt.Fprintln(&source, "// ErrUnavailable reports an unbound required Capability client.")
	fmt.Fprintln(&source, "var ErrUnavailable = errors.New(\"required Capability client is unavailable\")")
	fmt.Fprintln(&source)
	fmt.Fprintf(&source, "// Dependencies is the immutable generated Capability-client set for plugin %s.\n", pluginID)
	fmt.Fprintln(&source, "type Dependencies struct {")
	for _, dependency := range requirements {
		fmt.Fprintf(&source, "\tclient%s %s.Client\n", dependency.accessor, dependency.alias)
	}
	fmt.Fprintln(&source, "\tinitialized bool")
	fmt.Fprintln(&source, "}")
	fmt.Fprintln(&source)
	fmt.Fprintln(&source, "// New validates and binds every exact required Capability client.")
	fmt.Fprintln(&source, "func New(")
	for _, dependency := range requirements {
		fmt.Fprintf(&source, "\tclient%s %s.Client,\n", dependency.accessor, dependency.alias)
	}
	fmt.Fprintln(&source, ") (Dependencies, error) {")
	for _, dependency := range requirements {
		fmt.Fprintf(&source, "\tif !%s.Available(client%s) {\n", dependency.alias, dependency.accessor)
		fmt.Fprintln(&source, "\t\treturn Dependencies{}, ErrUnavailable")
		fmt.Fprintln(&source, "\t}")
	}
	fmt.Fprintln(&source, "\treturn Dependencies{")
	for _, dependency := range requirements {
		fmt.Fprintf(&source, "\t\tclient%s: client%s,\n", dependency.accessor, dependency.accessor)
	}
	fmt.Fprintln(&source, "\t\tinitialized: true,")
	fmt.Fprintln(&source, "\t}, nil")
	fmt.Fprintln(&source, "}")
	fmt.Fprintln(&source)
	fmt.Fprintln(&source, "// Valid reports whether every declared dependency was bound by application assembly.")
	fmt.Fprintln(&source, "func (d Dependencies) Valid() bool {")
	fmt.Fprintln(&source, "\tif !d.initialized {")
	fmt.Fprintln(&source, "\t\treturn false")
	fmt.Fprintln(&source, "\t}")
	for _, dependency := range requirements {
		fmt.Fprintf(&source, "\tif !%s.Available(d.client%s) {\n", dependency.alias, dependency.accessor)
		fmt.Fprintln(&source, "\t\treturn false")
		fmt.Fprintln(&source, "\t}")
	}
	fmt.Fprintln(&source, "\treturn true")
	fmt.Fprintln(&source, "}")
	for _, dependency := range requirements {
		fmt.Fprintln(&source)
		fmt.Fprintf(&source, "// %s returns the generated client for %s.\n", dependency.accessor, dependency.id)
		fmt.Fprintf(&source, "func (d Dependencies) %s() %s.Client {\n", dependency.accessor, dependency.alias)
		fmt.Fprintln(&source, "\tif !d.Valid() {")
		fmt.Fprintf(&source, "\t\treturn %s.Client{}\n", dependency.alias)
		fmt.Fprintln(&source, "\t}")
		fmt.Fprintf(&source, "\treturn d.client%s\n", dependency.accessor)
		fmt.Fprintln(&source, "}")
	}
	fmt.Fprintln(&source)
	fmt.Fprintln(&source, "// String redacts generated client handles.")
	fmt.Fprintln(&source, "func (Dependencies) String() string { return \"<generated-plugin-dependencies>\" }")
	fmt.Fprintln(&source)
	fmt.Fprintln(&source, "// GoString prevents Go-syntax formatting from exposing generated handles.")
	fmt.Fprintln(&source, "func (Dependencies) GoString() string { return \"<generated-plugin-dependencies>\" }")

	formatted, err := format.Source([]byte(source.String()))
	if err != nil {
		return File{}, fmt.Errorf("%w: format generated source: %w", ErrRender, err)
	}
	return File{
		path: path.Join("generated", "go", "dependencies", pluginName, "dependencies_gen.go"),
		data: append([]byte(nil), formatted...),
	}, nil
}

func capabilityAccessor(identifier capabilityid.Identifier) string {
	parts := strings.FieldsFunc(identifier.Name(), func(character rune) bool {
		return character == '.' || character == '-'
	})
	for index := range parts {
		parts[index] = goname.ExportedWord(parts[index])
	}
	return strings.Join(parts, "") + "V" + strconv.FormatUint(identifier.Major(), 10)
}

func clientImportPath(modulePath string, identifier capabilityid.Identifier) string {
	components := append([]string{modulePath, "generated", "go", "clients"}, strings.Split(identifier.Name(), ".")...)
	components = append(components, "v"+strconv.FormatUint(identifier.Major(), 10))
	return path.Join(components...)
}
