type renderedInterface struct {
	operation protobufmodel.InterfaceOperation
	segments  []string
	version   string
	symbol    string
	source    string
	transport transportOperation
}

func prepareInterfaces(model protobufmodel.InterfaceModel) ([]renderedInterface, error) {
	if !model.Valid() {
		return nil, nil
	}
	operations := model.Operations()
	if len(operations) != 0 && !model.Enabled() {
		return nil, fmt.Errorf("%w: JavaScript Interface methods require an enabled Connect projection", ErrRender)
	}
	result := make([]renderedInterface, len(operations))
	seen := make(map[string]string, len(operations))
	for index, operation := range operations {
		id := operation.ID()
		if id.String() == "" {
			return nil, fmt.Errorf("%w: Interface projection operations[%d] has an empty Interface ID", ErrRender, index)
		}
		if previous, duplicate := seen[id.String()]; duplicate {
			return nil, fmt.Errorf("%w: Interface projection duplicates %s at %s and %s", ErrRender, id, previous, operation.Source())
		}
		seen[id.String()] = operation.Source()
		segments := strings.Split(id.Name(), ".")
		version := "v" + strconv.FormatUint(id.Major(), 10)
		sourceComponents := append([]string{"src", "interfaces"}, segments...)
		sourceComponents = append(sourceComponents, version+".ts")
		identity := operation.Identity()
		result[index] = renderedInterface{
			operation: operation,
			segments:  segments,
			version:   version,
			source:    path.Join(sourceComponents...),
			transport: transportOperation{
				serviceType:  identity.Package() + "." + identity.Service(),
				methodName:   identity.Method(),
				requestType:  identity.RequestType(),
				responseType: identity.ResponseType(),
			},
		}
	}
	sort.Slice(result, func(left, right int) bool {
		return result[left].operation.ID().String() < result[right].operation.ID().String()
	})
	return result, nil
}

func discardSupersededLegacyOperations(operations []renderedOperation, interfaces []renderedInterface) []renderedOperation {
	if len(operations) == 0 || len(interfaces) == 0 {
		return operations
	}
	interfaceIDs := make(map[string]struct{}, len(interfaces))
	for _, operation := range interfaces {
		interfaceIDs[operation.operation.ID().String()] = struct{}{}
	}
	result := make([]renderedOperation, 0, len(operations))
	for _, operation := range operations {
		if _, superseded := interfaceIDs[operation.id.String()]; superseded {
			continue
		}
		if _, supersededTarget := interfaceIDs[operation.target.String()]; supersededTarget {
			continue
		}
		result = append(result, operation)
	}
	return result
}

func assignSurfaceSymbols(operations []renderedOperation, interfaces []renderedInterface) {
	baseByID := make(map[string]string, len(operations)+len(interfaces))
	for _, operation := range operations {
		baseByID[operation.id.String()] = operationSymbol(operation.id.Name(), operation.version)
	}
	for _, operation := range interfaces {
		id := operation.operation.ID()
		baseByID[id.String()] = operationSymbol(id.Name(), operation.version)
	}
	counts := make(map[string]int, len(baseByID))
	for _, base := range baseByID {
		counts[base]++
	}
	symbolByID := make(map[string]string, len(baseByID))
	for id, base := range baseByID {
		symbol := base
		if counts[base] > 1 {
			symbol += "_" + fmt.Sprintf("%x", []byte(id))
		}
		symbolByID[id] = symbol
	}
	for index := range operations {
		operations[index].symbol = symbolByID[operations[index].id.String()]
	}
	for index := range interfaces {
		interfaces[index].symbol = symbolByID[interfaces[index].operation.ID().String()]
	}
}

func renderInterfaceTypes(operation renderedInterface) ([]byte, error) {
	messages := operation.operation.Messages()
	if len(messages) < 2 {
		return nil, fmt.Errorf("%w: Interface %s has no complete request and response message graph", ErrRender, operation.operation.ID())
	}
	requestType, requestTypeFound := operation.operation.ProtobufMessageName(operation.operation.RequestGoName())
	responseType, responseTypeFound := operation.operation.ProtobufMessageName(operation.operation.ResponseGoName())
	if !requestTypeFound || !responseTypeFound {
		return nil, fmt.Errorf("%w: Interface %s message graph omits its canonical request or response identity", ErrRender, operation.operation.ID())
	}
	requestFound := false
	responseFound := false
	publicNames := make(map[string]string, len(messages))
	var source strings.Builder
	fmt.Fprintln(&source, "// Code generated by Plystra CLI. DO NOT EDIT.")
	fmt.Fprintln(&source)
	fmt.Fprintln(&source, "import {")
	fmt.Fprintln(&source, "  createRuntime,")
	fmt.Fprintln(&source, "  invokeInterface,")
	fmt.Fprintln(&source, "  type ClientOptions,")
	fmt.Fprintln(&source, "  type ErrorContract,")
	fmt.Fprintln(&source, "  type InterfaceCodec,")
	fmt.Fprintln(&source, "  type RequestOptions,")
	fmt.Fprintln(&source, "  type Runtime,")
	rootPrefix := strings.Repeat("../", len(operation.segments)+1)
	fmt.Fprintf(&source, "} from %s;\n", jsString(rootPrefix+"runtime.js"))
	fmt.Fprintf(&source, "import { resolveMessage, resolveUnaryMethod } from %s;\n\n", jsString(rootPrefix+"descriptors.js"))
	for _, message := range messages {
		if !javascriptIdentifier(message.ProtobufName()) {
			return nil, fmt.Errorf("%w: Interface %s message %s has invalid generated TypeScript identity %q", ErrRender, operation.operation.ID(), message.GoName(), message.ProtobufName())
		}
		switch message.GoName() {
		case operation.operation.RequestGoName():
			requestFound = true
		case operation.operation.ResponseGoName():
			responseFound = true
		}
		publicName := interfacePublicTypeName(operation, message)
		if previous, duplicate := publicNames[publicName]; duplicate {
			return nil, fmt.Errorf("%w: Interface %s messages %s and %s produce duplicate public TypeScript name %s", ErrRender, operation.operation.ID(), previous, message.GoName(), publicName)
		}
		publicNames[publicName] = message.GoName()
		fields := message.Fields()
		if len(fields) == 0 {
			fmt.Fprintf(&source, "export type %s = Readonly<Record<string, never>>;\n\n", message.ProtobufName())
			continue
		}
		fmt.Fprintf(&source, "export interface %s {\n", message.ProtobufName())
		for _, field := range fields {
			fieldType, err := interfaceTypeScriptType(operation.operation, field.Type())
			if err != nil {
				return nil, fmt.Errorf("%w: Interface %s message %s field %s: %v", ErrRender, operation.operation.ID(), message.GoName(), field.GoName(), err)
			}
			optional := ""
			if !field.Required() {
				optional = "?"
			}
			fmt.Fprintf(&source, "  readonly %s%s: %s;\n", jsString(field.JSONName()), optional, fieldType)
		}
		fmt.Fprintln(&source, "}")
		fmt.Fprintln(&source)
	}
	if !requestFound || !responseFound {
		return nil, fmt.Errorf("%w: Interface %s message graph omits its canonical request or response", ErrRender, operation.operation.ID())
	}
	renderInterfaceErrorCode(&source, operation.operation.SemanticErrors())
	fmt.Fprintln(&source, "export type Operation = (")
	fmt.Fprintf(&source, "  request: %s,\n", requestType)
	fmt.Fprintln(&source, "  options?: RequestOptions,")
	fmt.Fprintf(&source, ") => Promise<%s>;\n", responseType)
	fmt.Fprintf(&source, "export const interfaceID = %s;\n", jsString(operation.operation.ID().String()))
	fmt.Fprintf(&source, "export const contractDigest = %s;\n", jsString(operation.operation.ContractDigest()))
	renderMethodResolver(&source, operation.transport)
	fmt.Fprintf(&source, "const errorDetailDescriptor = resolveMessage(%s);\n", jsString(protobufdescriptor.ErrorDetailFullName))
	fmt.Fprintln(&source, "const semanticErrorCodes = Object.freeze([")
	for _, semanticErrorCode := range operation.operation.SemanticErrors() {
		fmt.Fprintf(&source, "  %s,\n", jsString(semanticErrorCode))
	}
	fmt.Fprintln(&source, "]);")
	fmt.Fprintln(&source)
	if err := renderInterfaceCodec(&source, operation); err != nil {
		return nil, err
	}
	fmt.Fprintln(&source)
	fmt.Fprintln(&source, "/** @internal */")
	fmt.Fprintln(&source, "export function bindOperation(runtime: Runtime): Operation {")
	fmt.Fprintln(&source, "  const errorContract: ErrorContract = {")
	fmt.Fprintln(&source, "    requestedCapabilityID: interfaceID,")
	fmt.Fprintln(&source, "    canonicalCapabilityID: interfaceID,")
	fmt.Fprintln(&source, "    semanticErrorCodes,")
	fmt.Fprintln(&source, "    detailDescriptor: errorDetailDescriptor,")
	fmt.Fprintln(&source, "  };")
	fmt.Fprintln(&source, "  return async (request, options = {}) =>")
	fmt.Fprintf(&source, "    (await invokeInterface(runtime, method, interfaceCodec, errorContract, request, options)) as %s;\n", responseType)
	fmt.Fprintln(&source, "}")
	fmt.Fprintln(&source)
	fmt.Fprintln(&source, "export function createOperation(options: ClientOptions): Operation {")
	fmt.Fprintln(&source, "  return bindOperation(createRuntime(options));")
	fmt.Fprintln(&source, "}")
	return []byte(strings.TrimRight(source.String(), "\n") + "\n"), nil
}

func renderInterfaceErrorCode(source *strings.Builder, errors []string) {
	if len(errors) == 0 {
		fmt.Fprintln(source, "export type ErrorCode = never;")
		fmt.Fprintln(source)
		return
	}
	values := make([]string, len(errors))
	for index, value := range errors {
		values[index] = jsString(value)
	}
	fmt.Fprintf(source, "export type ErrorCode = %s;\n\n", strings.Join(values, " | "))
}

func renderInterfaceCodec(source *strings.Builder, operation renderedInterface) error {
	fmt.Fprintln(source, "const interfaceCodec: InterfaceCodec = {")
	fmt.Fprintf(source, "  request: %s,\n", jsString(operation.operation.RequestGoName()))
	fmt.Fprintf(source, "  response: %s,\n", jsString(operation.operation.ResponseGoName()))
	fmt.Fprintln(source, "  messages: {")
	for _, message := range operation.operation.Messages() {
		fmt.Fprintf(source, "    %s: {\n", jsString(message.GoName()))
		fmt.Fprintln(source, "      fields: [")
		for _, field := range message.Fields() {
			value, err := interfaceValueCodecLiteral(operation.operation, field.Type())
			if err != nil {
				return fmt.Errorf("%w: Interface %s message %s field %s codec: %v", ErrRender, operation.operation.ID(), message.GoName(), field.GoName(), err)
			}
			fmt.Fprintln(source, "        {")
			fmt.Fprintf(source, "          canonicalName: %s,\n", jsString(field.JSONName()))
			fmt.Fprintf(source, "          protobufJSONName: %s,\n", jsString(field.JSONName()))
			fmt.Fprintf(source, "          required: %t,\n", field.Required())
			fmt.Fprintf(source, "          value: %s,\n", value)
			fmt.Fprintln(source, "        },")
		}
		fmt.Fprintln(source, "      ],")
		fmt.Fprintln(source, "    },")
	}
	fmt.Fprintln(source, "  },")
	fmt.Fprintln(source, "};")
	return nil
}

func interfaceValueCodecLiteral(operation protobufmodel.InterfaceOperation, value interfacecontract.Type) (string, error) {
	switch value.Kind() {
	case interfacecontract.TypeBoolean,
		interfacecontract.TypeString,
		interfacecontract.TypeInt32,
		interfacecontract.TypeInt64,
		interfacecontract.TypeUint32,
		interfacecontract.TypeUint64,
		interfacecontract.TypeFloat32,
		interfacecontract.TypeFloat64,
		interfacecontract.TypeBytes,
		interfacecontract.TypeTimestamp,
		interfacecontract.TypeDuration:
		return "{ kind: " + jsString(string(value.Kind())) + " }", nil
	case interfacecontract.TypeMessage:
		name, exists := value.MessageName()
		if !exists {
			return "", fmt.Errorf("message type has no canonical Go identity")
		}
		if _, exists := operation.ProtobufMessageName(name); !exists {
			return "", fmt.Errorf("message type %s has no generated identity", name)
		}
		return "{ kind: \"message\", message: " + jsString(name) + " }", nil
	case interfacecontract.TypeRepeated:
		element, exists := value.Element()
		if !exists {
			return "", fmt.Errorf("repeated type has no element")
		}
		rendered, err := interfaceValueCodecLiteral(operation, element)
		if err != nil {
			return "", err
		}
		return "{ kind: \"repeated\", element: " + rendered + " }", nil
	case interfacecontract.TypeMap:
		key, keyExists := value.Key()
		mapValue, valueExists := value.Value()
		if !keyExists || !valueExists {
			return "", fmt.Errorf("map type has no key or value")
		}
		if !interfaceMapKeyType(key.Kind()) {
			return "", fmt.Errorf("map key has unsupported type %s", key.Canonical())
		}
		rendered, err := interfaceValueCodecLiteral(operation, mapValue)
		if err != nil {
			return "", err
		}
		return "{ kind: \"map\", key: " + jsString(string(key.Kind())) + ", value: " + rendered + " }", nil
	default:
		return "", fmt.Errorf("unsupported canonical Interface type %q", value.Kind())
	}
}

func interfaceTypeScriptType(operation protobufmodel.InterfaceOperation, fieldType interfacecontract.Type) (string, error) {
	switch fieldType.Kind() {
	case interfacecontract.TypeBoolean:
		return "boolean", nil
	case interfacecontract.TypeString:
		return "string", nil
	case interfacecontract.TypeInt32, interfacecontract.TypeUint32:
		return "number", nil
	case interfacecontract.TypeInt64, interfacecontract.TypeUint64:
		return "bigint", nil
	case interfacecontract.TypeFloat32, interfacecontract.TypeFloat64:
		return "number", nil
	case interfacecontract.TypeBytes:
		return "Uint8Array", nil
	case interfacecontract.TypeTimestamp, interfacecontract.TypeDuration:
		return "string", nil
	case interfacecontract.TypeMessage:
		name, exists := fieldType.MessageName()
		if !exists {
			return "", fmt.Errorf("message type has no canonical Go identity")
		}
		generated, exists := operation.ProtobufMessageName(name)
		if !exists || !javascriptIdentifier(generated) {
			return "", fmt.Errorf("message type %s has no valid generated TypeScript identity", name)
		}
		return generated, nil
	case interfacecontract.TypeRepeated:
		element, exists := fieldType.Element()
		if !exists {
			return "", fmt.Errorf("repeated type has no element")
		}
		rendered, err := interfaceTypeScriptType(operation, element)
		if err != nil {
			return "", err
		}
		return "ReadonlyArray<" + rendered + ">", nil
	case interfacecontract.TypeMap:
		key, keyExists := fieldType.Key()
		value, valueExists := fieldType.Value()
		if !keyExists || !valueExists {
			return "", fmt.Errorf("map type has no key or value")
		}
		if !interfaceMapKeyType(key.Kind()) {
			return "", fmt.Errorf("map key has unsupported type %s", key.Canonical())
		}
		rendered, err := interfaceTypeScriptType(operation, value)
		if err != nil {
			return "", err
		}
		return "Readonly<Record<string, " + rendered + ">>", nil
	default:
		return "", fmt.Errorf("unsupported canonical Interface type %q", fieldType.Kind())
	}
}

func interfaceMapKeyType(kind interfacecontract.TypeKind) bool {
	switch kind {
	case interfacecontract.TypeBoolean,
		interfacecontract.TypeString,
		interfacecontract.TypeInt32,
		interfacecontract.TypeInt64,
		interfacecontract.TypeUint32,
		interfacecontract.TypeUint64:
		return true
	default:
		return false
	}
}

func interfacePublicTypeName(operation renderedInterface, message protobufmodel.InterfaceMessage) string {
	suffix := message.GoName()
	switch suffix {
	case operation.operation.RequestGoName():
		suffix = "Request"
	case operation.operation.ResponseGoName():
		suffix = "Response"
	}
	return operation.symbol + suffix
}

func interfacePublicTypeNameByGoName(operation renderedInterface, goName string) string {
	for _, message := range operation.operation.Messages() {
		if message.GoName() == goName {
			return interfacePublicTypeName(operation, message)
		}
	}
	return operation.symbol + goName
}

func interfaceIndexImportPath(operation renderedInterface) string {
	return "./" + strings.TrimSuffix(strings.TrimPrefix(operation.source, "src/"), ".ts") + ".js"
}

func interfaceClientAccessor(operation renderedInterface) string {
	components := append(append([]string(nil), operation.segments...), operation.version)
	var result strings.Builder
	for _, component := range components {
		if javascriptIdentifier(component) {
			result.WriteByte('.')
			result.WriteString(component)
		} else {
			result.WriteByte('[')
			result.WriteString(jsString(component))
			result.WriteByte(']')
		}
	}
	return result.String()
}
